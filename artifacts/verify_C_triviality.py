# For transparency we hard-code the elementary commutators used.
#
#   [a+, a-]_super  = {a+, a-} = 1          (fermion CAR)
#   [a+, a+]_super  = {a+, a+} = 0
#   [a-, a-]_super  = 0
#   [b_k^s, b_l^t]  = s*delta_{kl}*delta_{s,-t}   (sign: + if s=+,t=-)
#     explicitly: [b_k-, b_l+] = delta_{kl},   [b_k+, b_l-] = -delta_{kl}
#   [a^sigma, b_k^s]  = +gb_{sigma,k,s} kappa   (deformed, order a-b)
#     equivalently [b_k^s, a^sigma] = -gb_{sigma,k,s} kappa
#
# Everything is a polynomial in a+, a-, b_k+, b_k-, 1, and kappa.
# kappa is odd central; central numbers (incl. gb) commute with the generators
# at the level of the structure-constant computation we do here
# (we track only the g-valued component of  gamma  via identification
#  kappa * E_alpha  <->  gamma_contribution to E_alpha).


def build_basis(n):
    """
    Returns an ordered basis  [(name, parity, oscillator_rep)]  of C(n+1).

    oscillator_rep is a symbolic sympy expression in the generators
       Ap, Am, Bp[k], Bm[k]
    treated as non-commutative; multiplication is standard sympy.

    Parity: 0 = even, 1 = odd.
    """
    # Cartan
    basis = []

    # Fermionic charge (so(2)):  Z = Ap*Am - 1/2
    basis.append(("Z", 0, ("mon", (("a+", 1), ("a-", 1)))))

    # sp(2n) Cartan + roots.  We use the standard  E_{pm d_k pm d_l} = b_k^s b_l^t.
    for k in range(1, n + 1):
        basis.append((f"H_d{k}", 0, ("mon", ((f"b{k}+", 1), (f"b{k}-", 1)))))
        basis.append((f"E_2d{k}",  0, ("scalar_mon", sp.Rational(1, 2),
                                       ((f"b{k}+", 2),))))
        basis.append((f"E_-2d{k}", 0, ("scalar_mon", sp.Rational(1, 2),
                                       ((f"b{k}-", 2),))))
    for k in range(1, n + 1):
        for l in range(k + 1, n + 1):
            basis.append((f"E_d{k}+d{l}",  0, ("mon", ((f"b{k}+", 1), (f"b{l}+", 1)))))
            basis.append((f"E_-d{k}-d{l}", 0, ("mon", ((f"b{k}-", 1), (f"b{l}-", 1)))))
            basis.append((f"E_d{k}-d{l}",  0, ("mon", ((f"b{k}+", 1), (f"b{l}-", 1)))))
            basis.append((f"E_-d{k}+d{l}", 0, ("mon", ((f"b{k}-", 1), (f"b{l}+", 1)))))

    # Odd roots:  E_{+-eps +- d_k} = a^{sigma} b_k^s
    for k in range(1, n + 1):
        basis.append((f"E_e+d{k}",  1, ("mon", (("a+", 1), (f"b{k}+", 1)))))
        basis.append((f"E_e-d{k}",  1, ("mon", (("a+", 1), (f"b{k}-", 1)))))
        basis.append((f"E_-e+d{k}", 1, ("mon", (("a-", 1), (f"b{k}+", 1)))))
        basis.append((f"E_-e-d{k}", 1, ("mon", (("a-", 1), (f"b{k}-", 1)))))

    return basis


# ---------------------------------------------------------------------------
# 2. Normal-ordering engine (hand-rolled, polynomial of low degree).
# ---------------------------------------------------------------------------
#
# A monomial is a tuple of letters, each letter either 'a+','a-', or 'bk+'/'bk-'.
# We define an ordering (a+ < a- < b1+ < b1- < b2+ < b2- < ...) and
# reduce by applying the (deformed) elementary (anti-)commutation rules.
# All coefficients are sympy expressions in the  gb-symbols (and sp.Rational).

def letter_order(lett):
    if lett == 'a+': return 0
    if lett == 'a-': return 1
    sign = 0 if lett.endswith('+') else 1
    k = int(lett[1:-1])
    return 2 * (2 * (k - 1) + sign) + 2  # even integers starting at 2

def is_fermionic(lett):
    return lett in ('a+', 'a-')

def swap_rule(l1, l2, gb_symbols):
    """
    Returns (sign, extra) where swapping l1*l2 -> sign * l2*l1 + extra_term.
    extra_term is a dict  { tuple_of_letters : coeff }
    representing the correction terms produced by the (anti-)commutator.
    """
    f1 = is_fermionic(l1)
    f2 = is_fermionic(l2)
    # sign for pure swap under super-commutation
    if f1 and f2:
        sign = -1
    else:
        sign = 1

    extra = {}

    # Fermion CAR: {a+,a-} = 1  ->  a+ a- + a- a+ = 1
    if {l1, l2} == {'a+', 'a-'}:
        # l1 l2 = -l2 l1 + 1   (because of sign=-1 above we need +1 correction)
        extra[tuple()] = sp.Integer(1)

    # Boson CCR: [b_k-, b_l+] = delta_{kl}, [b_k+, b_l-] = -delta_{kl}
    if (not f1) and (not f2):
        k1, s1 = int(l1[1:-1]), l1[-1]
        k2, s2 = int(l2[1:-1]), l2[-1]
        if k1 == k2 and s1 != s2:
            # [l1, l2] = l1 l2 - l2 l1 = c
            # with sign=+1 (both bosons), l1 l2 = l2 l1 + c
            if s1 == '-' and s2 == '+':
                extra[tuple()] = sp.Integer(1)
            else:  # s1=='+' and s2=='-'
                extra[tuple()] = sp.Integer(-1)

    # Deformed a-b commutator (both b-letters commute with a up to central term)
    if f1 and (not f2):
        # l1 = a^sigma,  l2 = b_k^s
        sigma = l1[-1]
        k = int(l2[1:-1]); s = l2[-1]
        # [a^sigma, b_k^s] = +gb_{sigma,k,s} * kappa  (from [b,a] = -gb*kappa)
        # Since we are dropping kappa (we identify kappa*E_alpha ~ gamma into E_alpha)
        # the correction term lives in the kappa-sector.
        # Here we return the gb-correction as a special "kappa" marker.
        gb = gb_symbols[(sigma, k, s)]
        # l1 l2 = sign * l2 l1 + extra;  sign for fermion*boson is +1.
        # l1 l2 - l2 l1 = [l1, l2] = gb*kappa.  So extra_{(kappa,)} = gb.
        extra[(('KAPPA',),)] = gb  # marker; see processing below
    if (not f1) and f2:
        # l1 = b_k^s,  l2 = a^sigma
        sigma = l2[-1]
        k = int(l1[1:-1]); s = l1[-1]
        gb = gb_symbols[(sigma, k, s)]
        # [l1, l2] = -gb*kappa.   sign is +1, so l1 l2 = l2 l1 + extra
        extra[(('KAPPA',),)] = -gb

    return sign, extra


def normal_order(monom, gb_symbols, max_depth=50):
    """
    Reduce a monomial (tuple of letters) to a dict {tuple: coeff}
    in normal order (ascending letter_order) and separate out
    the "kappa-sector" terms (those containing the KAPPA marker).

    Returns two dicts:
      regular_terms   : {monom_tuple: coeff}        # no KAPPA factor
      kappa_terms     : {monom_tuple: coeff}        # KAPPA factor (coeff lin in gb)
    """
    regular = {monom: sp.Integer(1)}
    kappa   = {}

    changed = True
    depth = 0
    while changed and depth < max_depth:
        depth += 1
        changed = False
        new_regular = {}
        # scan each monomial in regular for an out-of-order adjacent pair
        for mon, coeff in regular.items():
            placed = False
            for i in range(len(mon) - 1):
                if letter_order(mon[i]) > letter_order(mon[i + 1]):
                    sign, extra = swap_rule(mon[i], mon[i + 1], gb_symbols)
                    swapped = mon[:i] + (mon[i + 1], mon[i]) + mon[i + 2:]
                    new_regular[swapped] = new_regular.get(swapped, 0) + sign * coeff
                    # extras:
                    for e_mon, e_coeff in extra.items():
                        # e_mon may contain the ('KAPPA',) marker
                        if len(e_mon) == 1 and e_mon[0] == ('KAPPA',):
                            # new monomial = mon[:i] + mon[i+2:], tagged KAPPA
                            new_tagged = mon[:i] + mon[i + 2:]
                            kappa[new_tagged] = kappa.get(new_tagged, 0) + coeff * e_coeff
                        else:
                            # bosonic/fermionic c-number from CAR/CCR
                            inserted = mon[:i] + e_mon + mon[i + 2:]
                            new_regular[inserted] = new_regular.get(inserted, 0) + coeff * e_coeff
                    changed = True
                    placed = True
                    break
            if not placed:
                new_regular[mon] = new_regular.get(mon, 0) + coeff
        regular = {k: sp.simplify(v) for k, v in new_regular.items() if sp.simplify(v) != 0}

        # also normal-order the kappa-sector monomials (they are regular g-generators)
        new_kappa = {}
        kappa_changed = True
        inner_depth = 0
        while kappa_changed and inner_depth < max_depth:
            inner_depth += 1
            kappa_changed = False
            new_kappa = {}
            for mon, coeff in kappa.items():
                placed = False
                for i in range(len(mon) - 1):
                    if letter_order(mon[i]) > letter_order(mon[i + 1]):
                        sign, extra = swap_rule(mon[i], mon[i + 1], gb_symbols)
                        swapped = mon[:i] + (mon[i + 1], mon[i]) + mon[i + 2:]
                        new_kappa[swapped] = new_kappa.get(swapped, 0) + sign * coeff
                        for e_mon, e_coeff in extra.items():
                            if len(e_mon) == 1 and e_mon[0] == ('KAPPA',):
                                # kappa * kappa = 0 (kappa is odd central -> square zero)
                                continue
                            inserted = mon[:i] + e_mon + mon[i + 2:]
                            new_kappa[inserted] = new_kappa.get(inserted, 0) + coeff * e_coeff
                        kappa_changed = True
                        placed = True
                        break
                if not placed:
                    new_kappa[mon] = new_kappa.get(mon, 0) + coeff
            kappa = {k: sp.simplify(v) for k, v in new_kappa.items() if sp.simplify(v) != 0}

    return regular, kappa


# ---------------------------------------------------------------------------
# 3.  Decompose a normal-ordered polynomial back into the basis of g.
# ---------------------------------------------------------------------------

def monomial_to_basis(basis):
    """ Returns {monomial_tuple: (basis_index, coeff)} for the basic g-generators. """
    table = {}
    for idx, (name, par, rep) in enumerate(basis):
        if rep[0] == "mon":
            flat = tuple()
            for lett, p in rep[1]:
                flat = flat + (lett,) * p
            table[flat] = (idx, sp.Integer(1), name)
        elif rep[0] == "scalar_mon":
            coeff = rep[1]
            letters = rep[2]
            # Expand (bk+, 2) -> (bk+, bk+)
            flat = tuple()
            for lett, p in letters:
                flat = flat + (lett,) * p
            table[flat] = (idx, coeff, name)
    return table

def normalize_basis_mon(rep):
    if rep[0] == "mon":
        flat = tuple()
        for lett, p in rep[1]:
            flat = flat + (lett,) * p
        return flat
    coeff = rep[1]
    letters = rep[2]
    flat = tuple()
    for lett, p in letters:
        flat = flat + (lett,) * p
    return flat


# ---------------------------------------------------------------------------
# 4.  Build the full gamma tensor and the coboundary tensor.
# ---------------------------------------------------------------------------

def compute_gamma(n):
    basis = build_basis(n)
    N = len(basis)

    # gb symbols: 4n parameters
    gb_symbols = {}
    for sigma in ('+', '-'):
        for k in range(1, n + 1):
            for s in ('+', '-'):
                gb_symbols[(sigma, k, s)] = sp.Symbol(f"gb_{sigma}{k}{s}")

    # basis lookup
    mon_to_basis = monomial_to_basis(basis)
    name_to_idx = {name: i for i, (name, _, _) in enumerate(basis)}

    # Precompute each basis element as a dict {monomial: coeff}
    def rep_as_poly(rep):
        if rep[0] == "mon":
            # rep[1] is of form ((lett, pow), ...) — flatten
            flat = tuple()
            for lett, p in rep[1]:
                flat = flat + (lett,) * p
            return {flat: sp.Integer(1)}
        return {normalize_basis_mon(rep): rep[1]}

    basis_polys = [rep_as_poly(rep) for _, _, rep in basis]

    # super-bracket of two g-elements, returns (regular_part, kappa_part)
    # each as a dict {monomial: coeff}.
    def super_bracket(i, j):
        pi = basis[i][1]
        pj = basis[j][1]
        sign_ij = -1 if (pi == 1 and pj == 1) else 1
        # [X, Y] = X Y  - sign_ij Y X
        reg = {}
        kap = {}
        for ma, ca in basis_polys[i].items():
            for mb, cb in basis_polys[j].items():
                # X Y
                r1, k1 = normal_order(ma + mb, gb_symbols)
                for m, c in r1.items():
                    reg[m] = reg.get(m, 0) + ca * cb * c
                for m, c in k1.items():
                    kap[m] = kap.get(m, 0) + ca * cb * c
                # Y X
                r2, k2 = normal_order(mb + ma, gb_symbols)
                for m, c in r2.items():
                    reg[m] = reg.get(m, 0) - sign_ij * ca * cb * c
                for m, c in k2.items():
                    kap[m] = kap.get(m, 0) - sign_ij * ca * cb * c
        reg = {m: sp.expand(v) for m, v in reg.items() if sp.expand(v) != 0}
        kap = {m: sp.expand(v) for m, v in kap.items() if sp.expand(v) != 0}
        return reg, kap

    # Decompose a normal-ordered polynomial (dict) into basis vector.
    # Only works for polys whose monomials are in the basis table or
    # the identity (treated as 0 in g — but Cartan has shifts that
    # we encoded without the constants, so we also allow the empty
    # monomial, which is dropped).
    def decompose(poly):
        vec = [sp.Integer(0)] * N
        residue = {}
        for mon, coeff in poly.items():
            if mon == tuple():
                continue  # constant -> dropped (central/identity)
            if mon in mon_to_basis:
                idx, c0, _ = mon_to_basis[mon]
                vec[idx] += coeff / c0
            else:
                residue[mon] = coeff
        return vec, residue

    # Build gamma as a 3-index tensor: gamma[i][j] = list of (basis_idx, coeff(gb))
    gamma = [[None] * N for _ in range(N)]
    structure = [[None] * N for _ in range(N)]
    for i in range(N):
        for j in range(N):
            reg, kap = super_bracket(i, j)
            vec_struct, _ = decompose(reg)
            vec_gamma,  _ = decompose(kap)
            structure[i][j] = vec_struct
            gamma[i][j]     = vec_gamma

    return basis, gb_symbols, structure, gamma


# ---------------------------------------------------------------------------
# 5.  Build the coboundary tensor  delta phi.
# ---------------------------------------------------------------------------

def coboundary_tensor(basis, structure):
    """
    Returns a sympy Matrix M such that  (delta phi) viewed as a flat vector
    (indexed by (i,j,c))  equals  M * phi_flat,
    where phi_flat is the vector of coefficients phi_{ij} of the odd map
    phi(Z_j) = sum_i phi_{ij} Z_i    (only entries with p(i) != p(j) kept).
    """
    N = len(basis)
    parity = [p for _, p, _ in basis]

    # Allowed (i,j) for phi: parity-flipping only.
    phi_indices = [(i, j) for i in range(N) for j in range(N)
                   if parity[i] != parity[j]]
    num_phi = len(phi_indices)

    # The output vector (gamma-shaped): index (I, J, c), parity (pI+pJ+1).
    # We only need to collect rows for (I,J,c) with p(c) = p(I)+p(J)+1 mod 2.
    out_indices = []
    for I in range(N):
        for J in range(N):
            for c in range(N):
                if parity[c] == (parity[I] + parity[J] + 1) % 2:
                    out_indices.append((I, J, c))
    num_out = len(out_indices)

    # Build the matrix.
    # (delta phi)(X_I, X_J) =
    #     (-1)^{p(I)} [X_I, phi(X_J)] - (-1)^{(p(I)+1)p(J)} [X_J, phi(X_I)]
    #   - phi([X_I, X_J])
    M = sp.zeros(num_out, num_phi)
    out_row = {idx: r for r, idx in enumerate(out_indices)}
    phi_col = {(i, j): c for c, (i, j) in enumerate(phi_indices)}

    for I in range(N):
        pI = parity[I]
        for J in range(N):
            pJ = parity[J]
            sign1 = (-1) ** pI
            sign2 = -((-1) ** ((pI + 1) * pJ))

            # Term 1: (-1)^pI * [X_I, phi(X_J)]
            # phi(X_J) = sum_i phi_{iJ} X_i  (over i with p(i) != p(J))
            for i in range(N):
                if parity[i] == parity[J]:
                    continue
                if (i, J) not in phi_col:
                    continue
                # [X_I, X_i] contributes to output c with coeff structure[I][i][c]
                vec = structure[I][i]
                for c in range(N):
                    coef = vec[c]
                    if coef == 0:
                        continue
                    key = (I, J, c)
                    if key not in out_row:
                        continue
                    M[out_row[key], phi_col[(i, J)]] += sign1 * coef

            # Term 2: - (-1)^{(pI+1)pJ} * [X_J, phi(X_I)]
            for i in range(N):
                if parity[i] == parity[I]:
                    continue
                if (i, I) not in phi_col:
                    continue
                vec = structure[J][i]
                for c in range(N):
                    coef = vec[c]
                    if coef == 0:
                        continue
                    key = (I, J, c)
                    if key not in out_row:
                        continue
                    M[out_row[key], phi_col[(i, I)]] += sign2 * coef

            # Term 3: - phi([X_I, X_J])  ->  - sum_j struct[I][J][j] * phi(X_j)
            #                             =  - sum_{i,j} struct[I][J][j] * phi_{ij} X_i
            for j in range(N):
                coef_j = structure[I][J][j]
                if coef_j == 0:
                    continue
                for i in range(N):
                    if parity[i] == parity[j]:
                        continue
                    if (i, j) not in phi_col:
                        continue
                    key = (I, J, i)
                    if key not in out_row:
                        continue
                    M[out_row[key], phi_col[(i, j)]] -= coef_j

    return M, phi_indices, out_indices


def gamma_flat(gamma, out_indices, gb_symbols):
    """ Flatten gamma into a column vector indexed by out_indices, linear in gb. """
    vec = sp.zeros(len(out_indices), 1)
    for r, (I, J, c) in enumerate(out_indices):
        vec[r, 0] = sp.expand(gamma[I][J][c])
    return vec


def triviality_dimension(n):
    """
    Returns a dict summarizing the triviality analysis for C(n+1).
    """
    print(f"\n=== n = {n},  g = C({n+1}) = osp(2|{2*n}) ===")
    basis, gb_symbols, structure, gamma = compute_gamma(n)
    N = len(basis)
    print(f"dim g = {N}")

    M, phi_indices, out_indices = coboundary_tensor(basis, structure)
    gamma_vec = gamma_flat(gamma, out_indices, gb_symbols)

    gb_list = list(gb_symbols.values())
    # Extract the coefficient matrix of gamma in gb_list:
    G = sp.zeros(len(out_indices), len(gb_list))
    for r in range(len(out_indices)):
        expr = gamma_vec[r, 0]
        for c_idx, g in enumerate(gb_list):
            G[r, c_idx] = expr.coeff(g)

    # "Up to scalar": lambda is just an overall rescaling of phi, so we can
    # absorb it into phi -> phi/lambda (both sides scale linearly in phi).
    # Hence  gamma = delta phi  has the same solution set as
    # G * gb = M * phi    i.e.  [G | -M] * (gb; phi) = 0.
    # The trivial-gb subspace is the projection of ker[G | -M] on the gb-factor.

    aug = sp.Matrix.hstack(G, -M)
    ns = aug.nullspace()
    # Dimension of projection of ker on first len(gb_list) coords:
    proj_vectors = [v[:len(gb_list), :] for v in ns]
    if proj_vectors:
        P = sp.Matrix.hstack(*proj_vectors)
        trivial_dim = P.rank()
    else:
        trivial_dim = 0

    print(f"dim(gb-parameter space)   = {len(gb_list)}")
    print(f"dim(odd phi space)        = {len(phi_indices)}")
    print(f"rank(coboundary map)      = {M.rank()}")
    print(f"dim(trivial gb subspace)  = {trivial_dim}")
    print(f"=> non-trivial deformations: {len(gb_list) - trivial_dim} directions")

    return {
        "n": n,
        "dim_g": N,
        "dim_gb_params": len(gb_list),
        "dim_odd_phi":  len(phi_indices),
        "rank_coboundary": int(M.rank()),
        "trivial_gb_dim": int(trivial_dim),
        "nontrivial_gb_dim": len(gb_list) - int(trivial_dim),
    }


