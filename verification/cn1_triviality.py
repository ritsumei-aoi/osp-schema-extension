"""Exact verification of the triviality of the inhomogeneous (gb) deformation of
C(n+1) = osp(2|2n), following docs/math/*.md.

Model
-----
U(A) is generated by  kappa (odd, central), a+, a- (odd), b_k^+, b_k^- (even)
with K = 1 and the (super)commutators
    [b_k^-, b_l^+] = delta_kl,   {a^-, a^+} = 1,   (a^+-)^2 = 0,
    [b_j^s, a^sigma] = -gb[sigma, j, s] * kappa,   kappa^2 = 0.
Elements are kept in normal order  kappa < a+ < a- < b_1^+..b_n^+ < b_1^-..b_n^-.

g = C(n+1) is the span of the quadratic normal-ordered monomials, taken modulo
scalars (the centre C.1 + C.kappa acts trivially in the adjoint representation;
this is the "up to scalar" clause of C_coboundary_definition.md, Sec. 3).

For basis elements X, Y the deformed bracket is written
    [X, Y]_gb = [X, Y]_0 + kappa * gamma(X, Y) + (central terms),
and we test  gamma = delta f  with
    (delta f)(X,Y) = (-1)^p(X) [X, f(Y)] - (-1)^((p(X)+1) p(Y)) [Y, f(X)] - f([X,Y]).

All arithmetic is exact (fractions.Fraction).  Results are written as JSON to
verification/artifacts/.
"""

from __future__ import annotations

import json
import random
from fractions import Fraction
from itertools import product
from pathlib import Path

import numpy as np

SIGMAS = ("+", "-")


# --------------------------------------------------------------------------
# Oscillator superalgebra U(A)
# --------------------------------------------------------------------------
class Osc:
    def __init__(self, n: int, gb: dict | None = None):
        self.n = n
        # generator indices
        self.KAPPA, self.AP, self.AM = 0, 1, 2
        self.BP = {k: 2 + k for k in range(1, n + 1)}
        self.BM = {k: 2 + n + k for k in range(1, n + 1)}
        self.names = {0: "kappa", 1: "a+", 2: "a-"}
        for k in range(1, n + 1):
            self.names[self.BP[k]] = f"b{k}+"
            self.names[self.BM[k]] = f"b{k}-"
        self.parity = {g: (1 if g in (0, 1, 2) else 0) for g in self.names}
        self.gb = {key: Fraction(v) for key, v in (gb or {}).items() if v != 0}

    def _bos(self, g):
        """(k, s) for a bosonic generator."""
        for k in range(1, self.n + 1):
            if g == self.BP[k]:
                return k, "+"
            if g == self.BM[k]:
                return k, "-"
        return None

    def _ferm(self, g):
        return {self.AP: "+", self.AM: "-"}.get(g)

    def abracket(self, y, x):
        """Super-bracket [y, x] in A (central): returns (coef_of_1, coef_of_kappa)."""
        if y == self.KAPPA or x == self.KAPPA:
            return Fraction(0), Fraction(0)
        by, bx = self._bos(y), self._bos(x)
        fy, fx = self._ferm(y), self._ferm(x)
        if by and bx:
            (k, s), (l, t) = by, bx
            if k != l or s == t:
                return Fraction(0), Fraction(0)
            return (Fraction(1) if s == "-" else Fraction(-1)), Fraction(0)
        if fy and fx:
            return (Fraction(1) if fy != fx else Fraction(0)), Fraction(0)
        if by and fx:  # [b_j^s, a^sigma] = -gb kappa
            j, s = by
            return Fraction(0), -self.gb.get((fx, j, s), Fraction(0))
        if fy and bx:  # [a^sigma, b_j^s] = +gb kappa
            j, s = bx
            return Fraction(0), self.gb.get((fy, j, s), Fraction(0))
        raise ValueError

    # elements: dict {tuple(monomial): Fraction}
    def normal(self, elem: dict) -> dict:
        out: dict = {}
        stack = list(elem.items())
        while stack:
            mono, c = stack.pop()
            if c == 0:
                continue
            if mono.count(self.KAPPA) > 1:
                continue
            for i in range(len(mono) - 1):
                y, x = mono[i], mono[i + 1]
                if y > x or (y == x and self.parity[y] == 1):
                    break
            else:
                out[mono] = out.get(mono, 0) + c
                continue
            pre, post = mono[:i], mono[i + 2:]
            if y == x:  # odd square = 1/2 [x, x]
                s1, sk = self.abracket(x, x)
                if s1:
                    stack.append((pre + post, c * s1 / 2))
                if sk:
                    stack.append((pre + (self.KAPPA,) + post, c * sk / 2))
                continue
            sign = -1 if self.parity[x] and self.parity[y] else 1
            stack.append((pre + (x, y) + post, c * sign))
            s1, sk = self.abracket(y, x)
            if s1:
                stack.append((pre + post, c * s1))
            if sk:
                stack.append((pre + (self.KAPPA,) + post, c * sk))
        return {m: v for m, v in out.items() if v != 0}

    def mul(self, A: dict, B: dict) -> dict:
        prod = {}
        for ma, ca in A.items():
            for mb, cb in B.items():
                m = ma + mb
                prod[m] = prod.get(m, 0) + ca * cb
        return self.normal(prod)

    def par(self, mono):
        return sum(self.parity[g] for g in mono) % 2

    def bracket(self, A: dict, B: dict, pa: int, pb: int) -> dict:
        ab, ba = self.mul(A, B), self.mul(B, A)
        sign = -1 if pa and pb else 1
        res = dict(ab)
        for m, v in ba.items():
            res[m] = res.get(m, 0) - sign * v
        return {m: v for m, v in res.items() if v != 0}


# --------------------------------------------------------------------------
# Basis of g = C(n+1) (modulo scalars)
# --------------------------------------------------------------------------
def build_basis(U: Osc):
    n = U.n
    basis = [(U.AP, U.AM)]  # so(2) part
    for k in range(1, n + 1):
        for l in range(k, n + 1):
            basis.append((U.BP[k], U.BP[l]))
    for k in range(1, n + 1):
        for l in range(1, n + 1):
            basis.append((U.BP[k], U.BM[l]))
    for k in range(1, n + 1):
        for l in range(k, n + 1):
            basis.append((U.BM[k], U.BM[l]))
    for a in (U.AP, U.AM):
        for k in range(1, n + 1):
            basis.append((a, U.BP[k]))
            basis.append((a, U.BM[k]))
    index = {m: i for i, m in enumerate(basis)}
    parities = [U.par(m) for m in basis]
    return basis, index, parities


def split(U: Osc, elem: dict, index: dict):
    """Split a normal-ordered element into
    (vec0, vecK, scal0, scalK): coordinates in g of the kappa-free part, of the
    kappa-coefficient, and the two scalar (central) parts."""
    D = len(index)
    v0, vK = [Fraction(0)] * D, [Fraction(0)] * D
    s0 = sK = Fraction(0)
    for m, c in elem.items():
        has_k = bool(m) and m[0] == U.KAPPA
        rest = m[1:] if has_k else m
        if len(rest) == 0:
            if has_k:
                sK += c
            else:
                s0 += c
        elif len(rest) == 2 and rest in index:
            (vK if has_k else v0)[index[rest]] += c
        else:
            raise RuntimeError(f"element leaves g: {m}")
    return v0, vK, s0, sK


def ell(U: Osc, sigma: str) -> dict:
    """l_sigma = sum_j ( gb[s,j,-] b_j^+ - gb[s,j,+] b_j^- )."""
    out = {}
    for j in range(1, U.n + 1):
        cp = U.gb.get((sigma, j, "-"), 0)
        cm = U.gb.get((sigma, j, "+"), 0)
        if cp:
            out[(U.BP[j],)] = Fraction(cp)
        if cm:
            out[(U.BM[j],)] = -Fraction(cm)
    return out


def explicit_f(U: Osc, basis):
    """Closed-form f_gb (as exact U(A)-elements, scalars included):
        f(b b)         = 0
        f(a^s b)       = - l_s b
        f(a^+ a^-)     = a^+ l_-  -  a^- l_+
    obtained from the substitution a^s = a'^s - kappa l_s."""
    lp, lm = ell(U, "+"), ell(U, "-")
    F = []
    for m in basis:
        if m == (U.AP, U.AM):
            t1 = U.mul({(U.AP,): Fraction(1)}, lm)
            t2 = U.mul({(U.AM,): Fraction(1)}, lp)
            val = dict(t1)
            for k, v in t2.items():
                val[k] = val.get(k, 0) - v
            F.append({k: v for k, v in val.items() if v != 0})
        elif m[0] in (U.AP, U.AM):
            l = lp if m[0] == U.AP else lm
            prod = U.mul(l, {(m[1],): Fraction(1)})
            F.append({k: -v for k, v in prod.items()})
        else:
            F.append({})
    return F


# --------------------------------------------------------------------------
# Main analysis for given n
# --------------------------------------------------------------------------
def analyse(n: int, seed: int = 0):
    U0 = Osc(n)
    basis, index, par = build_basis(U0)
    D = len(basis)
    elems = [{m: Fraction(1)} for m in basis]

    # structure constants of g (mod scalars) and closure check
    C = {}
    for i, j in product(range(D), repeat=2):
        br = U0.bracket(elems[i], elems[j], par[i], par[j])
        v0, vK, s0, sK = split(U0, br, index)
        assert not any(vK) and sK == 0
        C[(i, j)] = v0

    # super-Jacobi check on g mod scalars
    Csp = {key: [(m, c) for m, c in enumerate(v) if c] for key, v in C.items()}

    def br_vec(i, vec):
        out = [Fraction(0)] * D
        for k, c in enumerate(vec):
            if c:
                for m, cm in Csp[(i, k)]:
                    out[m] += c * cm
        return out

    jac_ok = True
    for i, j, k in product(range(D), repeat=3):
        lhs = br_vec(i, C[(j, k)])
        a = br_vec(k, C[(i, j)])  # [[i,j],k] = -(-1)^{(pi+pj)pk}[k,[i,j]]
        b = br_vec(j, C[(i, k)])
        sa = -(-1) ** (((par[i] + par[j]) * par[k]) % 2)
        sb = (-1) ** ((par[i] * par[j]) % 2)
        if any(lhs[m] - (sa * a[m] + sb * b[m]) for m in range(D)):
            jac_ok = False
            break

    # linear map phi -> delta f  (odd f only), for rank / image computations
    odd_slots = [(r, c) for r in range(D) for c in range(D) if par[r] != par[c]]
    slot_idx = {s: t for t, s in enumerate(odd_slots)}
    M = np.zeros((D * D * D, len(odd_slots)))
    for i, j in product(range(D), repeat=2):
        row0 = (i * D + j) * D
        pi, pj = par[i], par[j]
        s1 = (-1) ** pi
        s2 = -((-1) ** (((pi + 1) * pj) % 2))
        for k in range(D):
            # s1 [Z_i, f(Z_j)]   with f(Z_j) = sum_k phi_kj Z_k
            if (k, j) in slot_idx:
                for m in range(D):
                    if C[(i, k)][m]:
                        M[row0 + m, slot_idx[(k, j)]] += s1 * float(C[(i, k)][m])
            # s2 [Z_j, f(Z_i)]
            if (k, i) in slot_idx:
                for m in range(D):
                    if C[(j, k)][m]:
                        M[row0 + m, slot_idx[(k, i)]] += s2 * float(C[(j, k)][m])
            # - f([Z_i, Z_j]) = - sum_k C_ij^k phi_mk Z_m
            ck = C[(i, j)][k]
            if ck:
                for m in range(D):
                    if (m, k) in slot_idx:
                        M[row0 + m, slot_idx[(m, k)]] -= float(ck)
    rank = int(np.linalg.matrix_rank(M))
    kernel_dim = len(odd_slots) - rank

    # gb parameter list
    params = [(s, j, t) for s in SIGMAS for j in range(1, n + 1) for t in SIGMAS]
    rng = random.Random(seed + n)
    configs = {f"unit_gb[{s},{j},{t}]": {(s, j, t): 1} for (s, j, t) in params}
    configs["random_rational"] = {
        p: Fraction(rng.randint(-9, 9), rng.randint(1, 5)) for p in params
    }

    results = {}
    for name, gbv in configs.items():
        U = Osc(n, gbv)
        gamma, gamma_scal = {}, {}
        # kappa-part of deformed brackets
        for i, j in product(range(D), repeat=2):
            br = U.bracket(elems[i], elems[j], par[i], par[j])
            v0, vK, s0, sK = split(U, br, index)
            assert v0 == C[(i, j)], "kappa-free part must be undeformed"
            gamma[(i, j)] = vK
            gamma_scal[(i, j)] = sK

        # explicit f (exact U-elements) and its projection to g
        F = explicit_f(U, basis)
        Fvec, Fscal = [], []
        for fe in F:
            v0, vK, s0, sK = split(U0, fe, index)
            assert not any(vK) and sK == 0
            Fvec.append(v0)
            Fscal.append(s0)
        # parity check: f odd
        f_odd = all(
            all(c == 0 or par[m] != par[i] for m, c in enumerate(Fvec[i]))
            for i in range(D)
        )

        # delta f, computed with the abstract structure constants (mod scalars)
        def bracket_vec(vx, vy):
            out = [Fraction(0)] * D
            for a, ca in enumerate(vx):
                if ca:
                    for b, cb in enumerate(vy):
                        if cb:
                            for m in range(D):
                                if C[(a, b)][m]:
                                    out[m] += ca * cb * C[(a, b)][m]
            return out

        def f_of(vec):
            out = [Fraction(0)] * D
            for k, c in enumerate(vec):
                if c:
                    for m in range(D):
                        out[m] += c * Fvec[k][m]
            return out

        def s_of(vec):
            return sum((c * Fscal[k] for k, c in enumerate(vec)), Fraction(0))

        mismatch, scal_mismatch, nonzero_gamma = 0, 0, 0
        for i, j in product(range(D), repeat=2):
            ei = [Fraction(int(t == i)) for t in range(D)]
            ej = [Fraction(int(t == j)) for t in range(D)]
            pi, pj = par[i], par[j]
            t1 = bracket_vec(ei, Fvec[j])
            t2 = bracket_vec(ej, Fvec[i])
            t3 = f_of(C[(i, j)])
            df = [
                (-1) ** pi * t1[m]
                - (-1) ** (((pi + 1) * pj) % 2) * t2[m]
                - t3[m]
                for m in range(D)
            ]
            if df != gamma[(i, j)]:
                mismatch += 1
            if any(gamma[(i, j)]):
                nonzero_gamma += 1
            # central (kappa * 1) part: the same coboundary formula evaluated
            # exactly in U(A) (f with its scalar parts, brackets with theirs)
            c1 = split(U0, U0.bracket(elems[i], F[j], pi, 1 - pj), index)[2]
            c2 = split(U0, U0.bracket(elems[j], F[i], pj, 1 - pi), index)[2]
            expect = (
                (-1) ** pi * c1
                - (-1) ** (((pi + 1) * pj) % 2) * c2
                - s_of(C[(i, j)])
            )
            if gamma_scal[(i, j)] != expect:
                scal_mismatch += 1

        # independent check: gamma lies in the numerical image of delta
        g_vec = np.array(
            [float(gamma[(i, j)][m]) for i in range(D) for j in range(D) for m in range(D)]
        )
        sol, *_ = np.linalg.lstsq(M, g_vec, rcond=None)
        resid = float(np.linalg.norm(M @ sol - g_vec))

        results[name] = {
            "gb": {f"{s},{j},{t}": str(v) for (s, j, t), v in gbv.items()},
            "gamma_nonzero_pairs": nonzero_gamma,
            "gamma": {
                f"{i},{j}": {str(m): str(c) for m, c in enumerate(gamma[(i, j)]) if c}
                for i, j in product(range(D), repeat=2)
                if any(gamma[(i, j)])
            },
            "gamma_central_kappa_part": {
                f"{i},{j}": str(gamma_scal[(i, j)])
                for i, j in product(range(D), repeat=2)
                if gamma_scal[(i, j)]
            },
            "explicit_f": {
                str(i): {str(m): str(c) for m, c in enumerate(Fvec[i]) if c}
                for i in range(D)
                if any(Fvec[i])
            },
            "explicit_f_scalar_parts": {
                str(i): str(Fscal[i]) for i in range(D) if Fscal[i]
            },
            "f_is_odd": f_odd,
            "exact_check_gamma_eq_delta_f_mod_scalars": mismatch == 0,
            "exact_mismatch_pairs": mismatch,
            "central_part_equals_minus_s_of_bracket": scal_mismatch == 0,
            "lstsq_residual_gamma_in_image_delta": resid,
            "_gamma_vec": gamma,
        }

    # injectivity of gb -> gamma_gb (rank of the unit-configuration cocycles)
    unit_vecs = [
        [float(c) for i, j in product(range(D), repeat=2) for c in results[k]["_gamma_vec"][(i, j)]]
        for k in results
        if k.startswith("unit")
    ]
    gamma_map_rank = int(np.linalg.matrix_rank(np.array(unit_vecs)))
    for k in results:
        del results[k]["_gamma_vec"]

    def mname(m):
        return "*".join(U0.names[g] for g in m)

    return {
        "algebra": f"C({n + 1}) = osp(2|{2 * n})",
        "n": n,
        "dim_even": par.count(0),
        "dim_odd": par.count(1),
        "dim_total": D,
        "basis": [
            {"index": i, "monomial": mname(m), "parity": par[i]}
            for i, m in enumerate(basis)
        ],
        "structure_constants": {
            f"{i},{j}": {str(m): str(c) for m, c in enumerate(C[(i, j)]) if c}
            for i, j in product(range(D), repeat=2)
            if any(C[(i, j)])
        },
        "super_jacobi_ok": jac_ok,
        "delta_on_odd_maps": {
            "num_unknowns_phi": len(odd_slots),
            "rank": rank,
            "kernel_dim": kernel_dim,
            "kernel_expected_odd_inner_derivations": par.count(1),
        },
        "num_gb_parameters": len(params),
        "rank_of_gb_to_gamma_map": gamma_map_rank,
        "configs": results,
    }


def main():
    out_dir = Path(__file__).resolve().parent / "artifacts"
    out_dir.mkdir(exist_ok=True)
    summary = {}
    for n in (1, 2, 3):
        res = analyse(n)
        (out_dir / f"cn1_n{n}.json").write_text(json.dumps(res, indent=1))
        cfg = res["configs"]
        summary[f"n={n}"] = {
            "algebra": res["algebra"],
            "dims (even|odd)": f"{res['dim_even']}|{res['dim_odd']}",
            "super_jacobi_ok": res["super_jacobi_ok"],
            "delta_rank": res["delta_on_odd_maps"]["rank"],
            "delta_kernel_dim": res["delta_on_odd_maps"]["kernel_dim"],
            "num_gb_parameters": res["num_gb_parameters"],
            "rank_of_gb_to_gamma_map": res["rank_of_gb_to_gamma_map"],
            "all_configs_trivial_exact": all(
                c["exact_check_gamma_eq_delta_f_mod_scalars"] for c in cfg.values()
            ),
            "all_f_odd": all(c["f_is_odd"] for c in cfg.values()),
            "all_central_parts_consistent": all(
                c["central_part_equals_minus_s_of_bracket"] for c in cfg.values()
            ),
            "all_gamma_nonzero": all(c["gamma_nonzero_pairs"] > 0 for c in cfg.values()),
            "max_lstsq_residual": max(
                c["lstsq_residual_gamma_in_image_delta"] for c in cfg.values()
            ),
        }
        print(json.dumps({f"n={n}": summary[f"n={n}"]}, indent=1), flush=True)
    (out_dir / "summary.json").write_text(json.dumps(summary, indent=1))


if __name__ == "__main__":
    main()
