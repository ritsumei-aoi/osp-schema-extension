"""
Oscillator (Weyl-Clifford) algebra engine for C(n+1) = osp(2|2n).

Elements of the associative superalgebra generated by
    - a fermionic CAR pair a_1^+ (a_1_p), a_1^- (a_1_m):  {a^-, a^+} = 1, (a^±)^2 = 0
    - bosonic oscillators b_k^+ (b_k_p), b_k^- (b_k_m):     [b_k^-, b_l^+] = δ_kl
    - an optional odd central element kappa with kappa^2 = 0 (for the deformation, Schema 2)

are represented as dictionaries { monomial: coefficient }, where

    monomial = (kappa_flag, (letter, letter, ...))

is a normal-ordered word of oscillator letters, kappa_flag in {0, 1}, and the coefficient is a
sympy expression (rational, or polynomial in the gb deformation symbols).

A *letter* is a tuple (kind, index, sign):
    kind  in {'a', 'b'}         ('a' = fermion a_1, 'b' = boson)
    index int                    (0 for the fermion, 1..n for bosons)
    sign  in {+1, -1}            (+1 = creation ^+, -1 = annihilation ^-)

Normal ordering key (creations left of annihilations; fermion before bosons in each sign group):
    a^+ : (0, 0)       b_k^+ : (1, k)
    a^- : (2, 0)       b_k^- : (3, k)

The *graded commutator* [X, Y} = X*Y - (-1)^{p(X)p(Y)} Y*X is provided for Lie-superalgebra brackets.

The super-Jacobi identity is automatic: these are graded commutators in an associative
superalgebra, so any structure constants produced here satisfy super-Jacobi by construction.
"""

from __future__ import annotations
import sympy as sp

# ---- letters -------------------------------------------------------------

def a_p():        return ('a', 0, +1)
def a_m():        return ('a', 0, -1)
def b_p(k):       return ('b', k, +1)
def b_m(k):       return ('b', k, -1)

def is_fermion(letter):
    return letter[0] == 'a'

def order_key(letter):
    kind, index, sign = letter
    if kind == 'a':
        return (0, 0) if sign == +1 else (2, 0)
    else:  # boson
        return (1, index) if sign == +1 else (3, index)

# ---- polynomial type -----------------------------------------------------
# poly : dict mapping (kappa_flag, word_tuple) -> sympy coefficient

def poly_zero():
    return {}

def poly_add_term(poly, kappa_flag, word, coeff):
    if coeff == 0:
        return
    key = (kappa_flag, tuple(word))
    new = poly.get(key, sp.Integer(0)) + coeff
    if new == 0:
        poly.pop(key, None)
    else:
        poly[key] = new

def poly_add(dst, src):
    for (kf, word), c in src.items():
        poly_add_term(dst, kf, word, c)

def poly_scale(poly, scalar):
    out = poly_zero()
    for (kf, word), c in poly.items():
        poly_add_term(out, kf, word, scalar * c)
    return out

def mono(word, coeff=1, kappa_flag=0):
    """Build a (not-yet-normal-ordered) single-term polynomial, then normal order it."""
    base = {(kappa_flag, tuple(word)): sp.sympify(coeff)}
    return normal_order(base)

# ---- normal ordering -----------------------------------------------------

def normal_order(poly, gb=None):
    """
    Return the normal-ordered form of `poly`.

    gb : optional callable gb(sigma, j, s) -> sympy symbol giving the deformation parameter
         for [b_j^s, a_1^sigma] = - gb(sigma,j,s) * kappa.  If gb is None the algebra is
         undeformed ([b, a] = 0).  Deformation terms carry kappa_flag -> 1; kappa^2 = 0.
    """
    result = poly_zero()
    # worklist of (kappa_flag, list_of_letters, coeff)
    stack = [(kf, list(word), c) for (kf, word), c in poly.items()]
    while stack:
        kf, word, c = stack.pop()
        if c == 0:
            continue
        # nilpotency of fermion: any two identical adjacent fermion letters -> 0 handled in swaps;
        # also cancel (a^+)^2 / (a^-)^2 appearing anywhere after ordering groups them.
        idx = _first_out_of_order(word)
        if idx is None:
            # fully normal ordered; still must check fermion duplicates (nilpotency)
            if _has_fermion_square(word):
                continue
            poly_add_term(result, kf, word, c)
            continue
        L, R = word[idx], word[idx + 1]
        for (kf2, nword, c2) in _swap(kf, word, idx, L, R, c, gb):
            stack.append((kf2, nword, c2))
    return result

def _first_out_of_order(word):
    for i in range(len(word) - 1):
        if order_key(word[i]) > order_key(word[i + 1]):
            return i
    return None

def _has_fermion_square(word):
    for i in range(len(word) - 1):
        if word[i] == word[i + 1] and is_fermion(word[i]):
            return True
    return False

def _swap(kf, word, i, L, R, c, gb):
    """
    Resolve one out-of-order adjacency word[i]=L, word[i+1]=R (order_key(L) > order_key(R)).
    Yields a list of (kappa_flag, new_word, coeff) terms replacing the given word.

    Relations used:
      bosons:    b_k^- b_l^+ = b_l^+ b_k^- + δ_kl           (swap sign +1, correction δ)
                 any other same-sign/commuting boson pair: swap sign +1
      fermions:  a^- a^+ = -a^+ a^- + 1                     (swap sign -1, correction +1)
      ferm-bos:  undeformed [b,a]=0 -> swap sign +1, no correction
                 deformed: b_j^s a_1^σ = a_1^σ b_j^s - gb(σ,j,s) kappa   (when L=b, R=a)
                           a_1^σ b_j^s = b_j^s a_1^σ + gb(σ,j,s) kappa   (when L=a, R=b)
    """
    out = []
    prefix = word[:i]
    suffix = word[i + 2:]
    Lk, Rk = L[0], R[0]

    if Lk == 'b' and Rk == 'b':
        # swap, sign +1; correction only if conjugate pair L=b^-, R=b^+ same index
        out.append((kf, prefix + [R, L] + suffix, c))
        if L[2] == -1 and R[2] == +1 and L[1] == R[1]:
            out.append((kf, prefix + suffix, c))  # + δ * (rest)
        return out

    if Lk == 'a' and Rk == 'a':
        # only out-of-order case is a^- a^+ ; a^- a^+ = -a^+ a^- + 1
        out.append((kf, prefix + [R, L] + suffix, -c))
        out.append((kf, prefix + suffix, c))
        return out

    # mixed fermion/boson
    if gb is None:
        # undeformed: commute, sign +1, no correction
        out.append((kf, prefix + [R, L] + suffix, c))
        return out

    # deformed mixed swap (only creates a kappa term if kf == 0)
    out.append((kf, prefix + [R, L] + suffix, c))
    if kf == 0:
        if Lk == 'b' and Rk == 'a':
            # b_j^s a_1^σ -> a_1^σ b_j^s - gb(σ,j,s) kappa
            s = L[2]; sigma = R[2]; j = L[1]
            out.append((1, prefix + suffix, -c * gb(sigma, j, s)))
        elif Lk == 'a' and Rk == 'b':
            # a_1^σ b_j^s -> b_j^s a_1^σ + gb(σ,j,s) kappa
            sigma = L[2]; s = R[2]; j = R[1]
            out.append((1, prefix + suffix, c * gb(sigma, j, s)))
    return out

# ---- products and brackets ----------------------------------------------

def poly_mul(p, q, gb=None):
    out = poly_zero()
    for (kf1, w1), c1 in p.items():
        for (kf2, w2), c2 in q.items():
            if kf1 and kf2:
                continue  # kappa^2 = 0
            kf = kf1 + kf2
            term = {(kf, w1 + w2): c1 * c2}
            poly_add(out, normal_order(term, gb=gb))
    return out

def graded_commutator(X, pX, Y, pY, gb=None):
    """[X, Y} = X*Y - (-1)^{pX*pY} Y*X, with X,Y polynomials and pX,pY their parities (0/1)."""
    sign = -1 if (pX * pY) % 2 == 1 else 1
    xy = poly_mul(X, Y, gb=gb)
    yx = poly_mul(Y, X, gb=gb)
    out = poly_zero()
    poly_add(out, xy)
    poly_add(out, poly_scale(yx, sp.Integer(-sign)))
    return out

# ---- pretty print (debug) -----------------------------------------------

def letter_str(letter):
    kind, index, sign = letter
    s = '+' if sign == +1 else '-'
    if kind == 'a':
        return f"a1{s}"
    return f"b{index}{s}"

def poly_str(poly):
    if not poly:
        return "0"
    parts = []
    for (kf, word), c in sorted(poly.items(), key=lambda kv: (kv[0][0], len(kv[0][1]))):
        w = "*".join(letter_str(l) for l in word) if word else "1"
        k = "*kappa" if kf else ""
        parts.append(f"({c})*{w}{k}")
    return " + ".join(parts)
