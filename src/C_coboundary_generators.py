"""
C(n+1) Coboundary Structure (Schema 4) Generator.
Computes coboundary operator delta_f generated by odd linear map f: g -> g.
"""

import os
import json
from fractions import Fraction
from typing import Dict, List, Tuple, Any

def build_C_coboundary_structure(n: int) -> Dict[str, Any]:
    with open(f"data/C_{n}_structure.json") as f:
        struct_data = json.load(f)

    even_basis = struct_data["basis"]["even"]
    odd_basis = struct_data["basis"]["odd"]
    all_basis = odd_basis + even_basis
    parity_map = struct_data["parity"]

    dim_even = len(even_basis)
    dim_odd = len(odd_basis)
    param_count = 2 * dim_even * dim_odd

    # Build structure constant lookup table C[(x, y)][z] = Fraction
    C: Dict[Tuple[str, str], Dict[str, Fraction]] = {}
    for entry in struct_data["structure_constants"]:
        x, y, z = entry["X"], entry["Y"], entry["Z"]
        if (x, y) not in C:
            C[(x, y)] = {}
        C[(x, y)][z] = Fraction(entry["coeff"])

    def get_bracket(x: str, y: str) -> Dict[str, Fraction]:
        return C.get((x, y), {})

    coboundary_structure = []

    # Iterate over all pairs X, Y
    for x in all_basis:
        px = parity_map[x]
        for y in all_basis:
            py = parity_map[y]
            s1 = (-1) ** px
            s2 = - ((-1) ** ((px + 1) * py))

            # Store mapping: phi_{i,j} -> list of {Z, coeff}
            # phi_{i, j} means f(j) = sum_i phi_{i,j} i, where parity(i) != parity(j)
            delta_val_dict: Dict[str, Dict[str, Fraction]] = {}

            # Term 1: (-1)^p(X) [X, f(Y)] = (-1)^p(X) sum_{i} phi_{i, Y} [X, Z_i]
            # Here j = Y, i can be any generator with parity != py
            for zi in all_basis:
                if parity_map[zi] != py:
                    phi_param = f"phi_{zi}_{y}"
                    bracket = get_bracket(x, zi)
                    for zc, coeff in bracket.items():
                        c = Fraction(s1) * coeff
                        if phi_param not in delta_val_dict:
                            delta_val_dict[phi_param] = {}
                        delta_val_dict[phi_param][zc] = delta_val_dict[phi_param].get(zc, Fraction(0)) + c

            # Term 2: - (-1)^{(p(X)+1)p(Y)} [Y, f(X)] = s2 sum_{j} phi_{j, X} [Y, Z_j]
            # Here j_gen = X, i can be any generator with parity != px
            for zj in all_basis:
                if parity_map[zj] != px:
                    phi_param = f"phi_{zj}_{x}"
                    bracket = get_bracket(y, zj)
                    for zc, coeff in bracket.items():
                        c = Fraction(s2) * coeff
                        if phi_param not in delta_val_dict:
                            delta_val_dict[phi_param] = {}
                        delta_val_dict[phi_param][zc] = delta_val_dict[phi_param].get(zc, Fraction(0)) + c

            # Term 3: - f([X, Y]) = - f(sum_k C_{X,Y}^k Z_k) = - sum_k C_{X,Y}^k sum_c phi_{c, k} Z_c
            bracket_xy = get_bracket(x, y)
            for zk, c_xy in bracket_xy.items():
                pk = parity_map[zk]
                for zc in all_basis:
                    if parity_map[zc] != pk:
                        phi_param = f"phi_{zc}_{zk}"
                        c = - c_xy
                        if phi_param not in delta_val_dict:
                            delta_val_dict[phi_param] = {}
                        delta_val_dict[phi_param][zc] = delta_val_dict[phi_param].get(zc, Fraction(0)) + c

            # Filter non-zero terms
            delta_val_json = {}
            for phi_param, z_map in delta_val_dict.items():
                non_zero_terms = [
                    {"Z": zc, "coeff": str(coeff)} for zc, coeff in z_map.items() if coeff != 0
                ]
                if non_zero_terms:
                    delta_val_json[phi_param] = non_zero_terms

            if delta_val_json:
                coboundary_structure.append({
                    "X": x,
                    "Y": y,
                    "delta_f_value": delta_val_json
                })

    schema_data = {
        "schema_version": "5.0",
        "algebra": {
            "family": "C",
            "m": 1,
            "n": n,
            "cartan_type": f"C({n+1})"
        },
        "f_matrix_info": {
            "even_dim": dim_even,
            "odd_dim": dim_odd,
            "parameter_count": param_count,
            "description": "Linear map f: g -> g reversing parity, parameterized by phi_{target}_{source}"
        },
        "coboundary_structure": coboundary_structure,
        "metadata": {
            "generated_by": "src/C_coboundary_generators.py",
            "generation_date": "2026-10-05"
        }
    }

    return schema_data


def generate_all_coboundary():
    os.makedirs("data", exist_ok=True)
    for n in [1, 2, 3]:
        data = build_C_coboundary_structure(n)
        filepath = f"data/C_{n}_coboundary.json"
        with open(filepath, "w") as f:
            json.dump(data, f, indent=2)
        print(f"Generated {filepath} (coboundary entries: {len(data['coboundary_structure'])})")


if __name__ == "__main__":
    generate_all_coboundary()
