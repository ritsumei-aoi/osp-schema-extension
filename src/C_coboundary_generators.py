import json
from fractions import Fraction
from typing import Dict, List, Tuple, Any
from src.C_generators import CAlgebra

def compute_coboundary_coefficients(n: int) -> Dict[str, Any]:
    with open(f"data/C_{n}_structure.json", "r") as f:
        schema1 = json.load(f)

    basis_even = schema1["basis"]["even"]
    basis_odd = schema1["basis"]["odd"]
    # Include K in even basis candidates if needed
    basis_all = basis_odd + basis_even
    parity = schema1["parity"]

    # Candidate target elements for f:
    # f maps g_0 -> g_1 (or odd basis)
    # f maps g_1 -> g_0 or K
    even_targets = basis_even + ["K"]
    odd_targets = list(basis_odd)

    # Map brackets from Schema 1: (X, Y) -> Dict[Z, Fraction]
    bracket_map: Dict[Tuple[str, str], Dict[str, Fraction]] = {}
    for sc in schema1["structure_constants"]:
        x, y, z = sc["X"], sc["Y"], sc["Z"]
        if (x, y) not in bracket_map:
            bracket_map[(x, y)] = {}
        bracket_map[(x, y)][z] = Fraction(sc["coeff"])

    def get_bracket(x: str, y: str) -> Dict[str, Fraction]:
        return bracket_map.get((x, y), {})

    # Build elementary odd linear maps f_{Z_i, Z_j} (maps Z_j -> Z_i with p(Z_i) != p(Z_j))
    # map_param name: "phi_{Z_i}_{Z_j}"
    map_params = []
    
    # 1. Z_j is even (in basis_even), Z_i is odd (in odd_targets)
    for zj in basis_even:
        for zi in odd_targets:
            map_params.append((zi, zj)) # f(zj) = zi

    # 2. Z_j is odd (in basis_odd), Z_i is even (in even_targets)
    for zj in basis_odd:
        for zi in even_targets:
            map_params.append((zi, zj)) # f(zj) = zi

    coboundary_sc_list = []

    # Compute delta f_{zi, zj}(X, Y) for each elementary map (zi, zj) and generator pair (X, Y)
    for zi, zj in map_params:
        param_name = f"phi_{zi}_{zj}"
        pzj = parity.get(zj, 0)
        pzi = parity.get(zi, 1 if zj in basis_even else 0)

        for i, x in enumerate(basis_all):
            px = parity[x]
            for j, y in enumerate(basis_all):
                py = parity[y]

                res: Dict[str, Fraction] = {}

                # Term 1: (-1)^{px} [X, f(Y)] if Y == zj
                if y == zj:
                    s1 = -1 if px == 1 else 1
                    # [X, zi]
                    bracket_x_zi = get_bracket(x, zi)
                    for z, c in bracket_x_zi.items():
                        res[z] = res.get(z, Fraction(0)) + s1 * c

                # Term 2: - (-1)^{(px+1)py} [Y, f(X)] if X == zj
                if x == zj:
                    sign_exp = (px + 1) * py
                    s2 = -1 if (sign_exp % 2 == 1) else 1
                    # - s2 * [Y, zi]
                    bracket_y_zi = get_bracket(y, zi)
                    for z, c in bracket_y_zi.items():
                        res[z] = res.get(z, Fraction(0)) - s2 * c

                # Term 3: - f([X, Y]) = - c_{X, Y}^{zj} zi
                b_xy = get_bracket(x, y)
                if zj in b_xy:
                    c_zj = b_xy[zj]
                    res[zi] = res.get(zi, Fraction(0)) - c_zj

                # Clean zeros
                for z, c in list(res.items()):
                    if c == 0:
                        del res[z]
                    else:
                        c_str = str(c.numerator) if c.denominator == 1 else f"{c.numerator}/{c.denominator}"
                        coboundary_sc_list.append({
                            "X": x,
                            "Y": y,
                            "Z": z,
                            "map_param": param_name,
                            "coeff": c_str
                        })

    schema4 = dict(schema1)
    schema4["schema_version"] = "5.0"
    schema4["coboundary_structure"] = {
        "description": "Coboundary operator delta f generated by elementary odd linear maps f_{Z_i, Z_j}: g -> g",
        "map_parameters": [f"phi_{zi}_{zj}" for zi, zj in map_params],
        "coboundary_coefficients": coboundary_sc_list
    }

    return schema4


if __name__ == "__main__":
    import os
    os.makedirs("data", exist_ok=True)
    for n in [1, 2, 3]:
        data = compute_coboundary_coefficients(n)
        filename = f"data/C_{n}_coboundary.json"
        with open(filename, "w") as f:
            json.dump(data, f, indent=2)
        print(f"Generated {filename} (Coboundary terms: {len(data['coboundary_structure']['coboundary_coefficients'])})")
