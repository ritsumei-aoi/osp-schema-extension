def build_odd_linear_map(n: int, basis: List[str], parities: Dict[str, int]) -> Dict[str, Dict[str, Fraction]]:
    """Define the canonical odd linear map f: g -> g reversing parity:
    p(f(X)) = 1 - p(X).
    """
    f_map = defaultdict(lambda: defaultdict(Fraction))

    # 1. Odd -> Even sector (g_1 -> g_0)
    for k in range(1, n + 1):
        f_map[f"E_eps1_del{k}_pp"]["H_1"] -= 1
        f_map[f"E_eps1_del{k}_pp"][f"H_{k+1}"] -= 1

        f_map[f"E_eps1_del{k}_pm"]["H_1"] -= 1
        f_map[f"E_eps1_del{k}_pm"][f"H_{k+1}"] -= 1

        f_map[f"E_eps1_del{k}_mp"]["H_1"] += 1
        f_map[f"E_eps1_del{k}_mp"][f"H_{k+1}"] += 1

        f_map[f"E_eps1_del{k}_mm"]["H_1"] += 1
        f_map[f"E_eps1_del{k}_mm"][f"H_{k+1}"] += 1

    # 2. Even -> Odd sector (g_0 -> g_1)
    for k in range(1, n + 1):
        for s in ["pp", "pm", "mp", "mm"]:
            f_map["H_1"][f"E_eps1_del{k}_{s}"] += 1
            f_map[f"H_{n+1}"][f"E_eps1_del{k}_{s}"] -= 1

        f_map[f"E_2del{k}_p"][f"E_eps1_del{k}_pp"] += 2
        f_map[f"E_2del{k}_p"][f"E_eps1_del{k}_mp"] += 2

        f_map[f"E_2del{k}_m"][f"E_eps1_del{k}_pm"] += 2
        f_map[f"E_2del{k}_m"][f"E_eps1_del{k}_mm"] += 2

    for k in range(2, n + 1):
        for s in ["pp", "pm", "mp", "mm"]:
            f_map[f"H_{k}"][f"E_eps1_del{k-1}_{s}"] += 1
            f_map[f"H_{k}"][f"E_eps1_del{k}_{s}"] -= 1

    # Short even roots (for n >= 2)
    for i in range(1, n + 1):
        for j in range(i + 1, n + 1):
            f_map[f"E_del{i}_del{j}_pp"][f"E_eps1_del{i}_pp"] += 1
            f_map[f"E_del{i}_del{j}_pp"][f"E_eps1_del{j}_pp"] += 1
            f_map[f"E_del{i}_del{j}_pp"][f"E_eps1_del{i}_mp"] += 1
            f_map[f"E_del{i}_del{j}_pp"][f"E_eps1_del{j}_mp"] += 1

            f_map[f"E_del{i}_del{j}_mm"][f"E_eps1_del{i}_pm"] += 1
            f_map[f"E_del{i}_del{j}_mm"][f"E_eps1_del{j}_pm"] += 1
            f_map[f"E_del{i}_del{j}_mm"][f"E_eps1_del{i}_mm"] += 1
            f_map[f"E_del{i}_del{j}_mm"][f"E_eps1_del{j}_mm"] += 1

            f_map[f"E_del{i}_del{j}_pm"][f"E_eps1_del{i}_pp"] += 1
            f_map[f"E_del{i}_del{j}_pm"][f"E_eps1_del{i}_mp"] += 1
            f_map[f"E_del{i}_del{j}_pm"][f"E_eps1_del{j}_pm"] -= 1
            f_map[f"E_del{i}_del{j}_pm"][f"E_eps1_del{j}_mm"] -= 1

            f_map[f"E_del{i}_del{j}_mp"][f"E_eps1_del{i}_pm"] -= 1
            f_map[f"E_del{i}_del{j}_mp"][f"E_eps1_del{i}_mm"] -= 1
            f_map[f"E_del{i}_del{j}_mp"][f"E_eps1_del{j}_pp"] += 1
            f_map[f"E_del{i}_del{j}_mp"][f"E_eps1_del{j}_mp"] += 1

    # Verify parity reversal
    for src, targets in f_map.items():
        p_src = parities[src]
        for tgt, c in targets.items():
            if c != 0:
                assert parities[tgt] == 1 - p_src, f"Parity reversal violation: {src} -> {tgt}"

    return f_map


def compute_coboundary(n: int) -> Tuple[List[Dict[str, str]], Dict[str, Dict[str, str]]]:
    """Compute (delta f)(X, Y) = (-1)^pX [X, f(Y)] - (-1)^{(pX+1)pY} [Y, f(X)] - f([X, Y])."""
    with open(f"data/C_{n}_structure.json", "r") as f:
        sdata = json.load(f)

    basis = sdata["basis"]["odd"] + sdata["basis"]["even"]
    parities = sdata["parity"]

    bracket = defaultdict(dict)
    for entry in sdata["structure_constants"]:
        bracket[(entry["X"], entry["Y"])][entry["Z"]] = Fraction(entry["coeff"])

    f_map = build_odd_linear_map(n, basis, parities)

    coboundary_entries = []
    delta_dict = defaultdict(dict)

    for X in basis:
        pX = parities[X]
        for Y in basis:
            pY = parities[Y]
            res = defaultdict(Fraction)

            # Term 1: (-1)^pX [X, f(Y)]
            s1 = (-1)**pX
            for Z_fY, c_fY in f_map.get(Y, {}).items():
                for Z, c_xz in bracket.get((X, Z_fY), {}).items():
                    res[Z] += s1 * c_fY * c_xz

            # Term 2: - (-1)^{(pX+1)pY} [Y, f(X)]
            s2 = - ((-1)**((pX + 1) * pY))
            for Z_fX, c_fX in f_map.get(X, {}).items():
                for Z, c_yz in bracket.get((Y, Z_fX), {}).items():
                    res[Z] += s2 * c_fX * c_yz

            # Term 3: - f([X, Y])
            for Z_xy, c_xy in bracket.get((X, Y), {}).items():
                for Z, c_fZ in f_map.get(Z_xy, {}).items():
                    res[Z] -= c_xy * c_fZ

            for Z, coeff in sorted(res.items()):
                if coeff != 0:
                    delta_dict[(X, Y)][Z] = coeff
                    coboundary_entries.append({
                        "X": X,
                        "Y": Y,
                        "Z": Z,
                        "coeff": str(coeff) if coeff.denominator != 1 else str(coeff.numerator),
                        "sign_rule": "graded"
                    })

    # Format f_map representation for JSON
    f_formatted = {}
    for src in basis:
        targets = f_map.get(src, {})
        tgt_dict = {tgt: str(c) if c.denominator != 1 else str(c.numerator) for tgt, c in sorted(targets.items()) if c != 0}
        if tgt_dict:
            f_formatted[src] = tgt_dict

    return coboundary_entries, f_formatted


def generate_schema4_json(n: int) -> Dict[str, Any]:
    with open(f"data/C_{n}_structure.json", "r") as f:
        sdata = json.load(f)

    coboundary_entries, f_formatted = compute_coboundary(n)

    data = {
        "schema_version": "5.0",
        "algebra": sdata["algebra"],
        "basis": sdata["basis"],
        "parity": sdata["parity"],
        "linear_map_f": {
            "description": "Odd linear map f: g -> g reversing parity (p(f(X)) = 1 - p(X))",
            "mapping": f_formatted
        },
        "coboundary": {
            "description": "Coboundary operator (delta f)(X, Y) = (-1)^p(X) [X, f(Y)] - (-1)^{(p(X)+1)p(Y)} [Y, f(X)] - f([X, Y])",
            "sign_rule": "graded: (delta f)(Y, X) = -(-1)^{p(X)p(Y)} (delta f)(X, Y)",
            "total_entries": len(coboundary_entries),
            "coefficients": coboundary_entries
        },
        "metadata": {
            "generated_by": "src/C_coboundary_generator.py",
            "generation_date": "2026-10-04",
            "references": [
                "docs/math/C_coboundary_definition.md"
            ]
        }
    }
    return data


def main():
    os.makedirs("data", exist_ok=True)
    for n in [1, 2, 3]:
        t0 = time.time()
        print(f"Generating Schema 4 C_{n}_coboundary.json for C({n+1}) = osp(2|{2*n})...")
        data = generate_schema4_json(n)
        filepath = f"data/C_{n}_coboundary.json"
        with open(filepath, "w") as f:
            json.dump(data, f, indent=2)
        total = data["coboundary"]["total_entries"]
        print(f"  Saved {filepath}: {total} coboundary entries ({time.time() - t0:.2f}s).")


if __name__ == "__main__":
    main()
