"""
C_coboundary_generator.py: Generates Schema 4 (Coboundary Structure) for C(n+1) = osp(2|2n).
Implements the coboundary operator (delta f)(X, Y) generated by an odd linear map f: g -> g.
Following docs/math/C_coboundary_definition.md.
"""

import json
import os
import sys
import time
from collections import defaultdict
from fractions import Fraction
from typing import Dict, List, Tuple, Any

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

