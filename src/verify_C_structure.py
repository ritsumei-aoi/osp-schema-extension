"""Verify C(n+1) structure constants: antisymmetry and super Jacobi.

Loads ``data/C_{n}_structure.json`` for n in {1,2,3} and checks:

1. For every stored bracket (X, Y, Z, coeff), reconstructs the implied
   bracket of oscillator realizations and compares against the direct
   oscillator graded bracket.
2. Antisymmetry: [X, Y} = -(-1)^{p(X)p(Y)} [Y, X} computed in oscillators.
3. Super Jacobi: (-1)^{p(X)p(Z)}[X,[Y,Z}} + cyclic = 0, over all basis
   triples (verified in oscillator form; proves Jacobi for the Lie
   sub-superalgebra generated by the basis).
"""

from __future__ import annotations

import json
import os
import sys
from collections import defaultdict
from fractions import Fraction
from typing import Dict, List, Tuple

from src.C_generators import build_basis, recombine
from src.C_oscillator import Poly, graded_bracket, poly_add


def load_structure(n: int) -> dict:
    path = os.path.join(
        os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
        "data",
        f"C_{n}_structure.json",
    )
    with open(path) as f:
        return json.load(f)


def group_structure_constants(sc):
    """Group by (X,Y) → list of (Z, Fraction(coeff))."""
    g: Dict[Tuple[str, str], List[Tuple[str, Fraction]]] = defaultdict(list)
    for e in sc:
        g[(e["X"], e["Y"])].append((e["Z"], Fraction(e["coeff"])))
    return g


def verify_against_stored(n: int):
    even, odd, reals, pars = build_basis(n)
    labels = even + odd
    data = load_structure(n)
    grouped = group_structure_constants(data["structure_constants"])
    errors = []
    for i, X in enumerate(labels):
        for Y in labels[i:]:
            br = graded_bracket(reals[X], reals[Y], pars[X], pars[Y])
            stored = grouped.get((X, Y), [])
            coeffs = {Z: c for Z, c in stored}
            rec = recombine(coeffs, reals)
            diff = poly_add(br, rec, Fraction(-1))
            if diff:
                errors.append((X, Y, diff))
    return errors


def verify_antisymmetry(n: int):
    even, odd, reals, pars = build_basis(n)
    labels = even + odd
    errors = []
    for X in labels:
        for Y in labels:
            br_xy = graded_bracket(reals[X], reals[Y], pars[X], pars[Y])
            br_yx = graded_bracket(reals[Y], reals[X], pars[Y], pars[X])
            sign = 1 if (pars[X] * pars[Y]) % 2 == 0 else -1
            # [X,Y} + sign*[Y,X} = 0 ?
            s = poly_add(br_xy, br_yx, Fraction(sign))
            if s:
                errors.append((X, Y, s))
    return errors


def verify_super_jacobi(n: int):
    even, odd, reals, pars = build_basis(n)
    labels = even + odd
    errors = []
    for X in labels:
        for Y in labels:
            br_YZ_cache = {}
            for Z in labels:
                pX, pY, pZ = pars[X], pars[Y], pars[Z]
                # (-1)^{pX pZ}[X,[Y,Z}} + (-1)^{pY pX}[Y,[Z,X}} + (-1)^{pZ pY}[Z,[X,Y}}
                brYZ = graded_bracket(reals[Y], reals[Z], pY, pZ)
                brZX = graded_bracket(reals[Z], reals[X], pZ, pX)
                brXY = graded_bracket(reals[X], reals[Y], pX, pY)
                t1 = graded_bracket(reals[X], brYZ, pX, (pY + pZ) % 2)
                t2 = graded_bracket(reals[Y], brZX, pY, (pZ + pX) % 2)
                t3 = graded_bracket(reals[Z], brXY, pZ, (pX + pY) % 2)
                s = {}
                sgn1 = 1 if (pX * pZ) % 2 == 0 else -1
                sgn2 = 1 if (pY * pX) % 2 == 0 else -1
                sgn3 = 1 if (pZ * pY) % 2 == 0 else -1
                s = poly_add(s, t1, Fraction(sgn1))
                s = poly_add(s, t2, Fraction(sgn2))
                s = poly_add(s, t3, Fraction(sgn3))
                if s:
                    errors.append((X, Y, Z, s))
    return errors


def main():
    report = []
    overall_ok = True
    for n in (1, 2, 3):
        report.append(f"=== n = {n} (C({n + 1})) ===")
        stored_errs = verify_against_stored(n)
        anti_errs = verify_antisymmetry(n)
        jac_errs = verify_super_jacobi(n)
        report.append(f"  stored-vs-oscillator mismatches: {len(stored_errs)}")
        report.append(f"  antisymmetry failures:           {len(anti_errs)}")
        report.append(f"  super-Jacobi failures:           {len(jac_errs)}")
        if stored_errs or anti_errs or jac_errs:
            overall_ok = False
            for X, Y, d in stored_errs[:3]:
                report.append(f"    stored[{X},{Y}] residual: {d}")
            for X, Y, d in anti_errs[:3]:
                report.append(f"    anti[{X},{Y}] residual: {d}")
            for X, Y, Z, d in jac_errs[:3]:
                report.append(f"    jacobi[{X},{Y},{Z}] residual: {d}")
    report.append("")
    report.append("PASS" if overall_ok else "FAIL")
    txt = "\n".join(report)
    print(txt)
    return 0 if overall_ok else 1


if __name__ == "__main__":
    sys.exit(main())
