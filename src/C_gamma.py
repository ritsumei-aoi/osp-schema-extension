"""
C(n+1) = osp(2|2n) Inhomogeneous Deformation (Gamma Structure) Generator
Generates Schema 2 v5.0 JSON specifications for n=1, 2, 3.

Mathematical Definition:
The inhomogeneous deformation of C(n+1) is defined by the exchange relations
  [b_j^s, a_1^sigma] = - gb_{sigma, j, s} * kappa
in the universal enveloping algebra U(A) of the extended oscillator algebra
A = V + C*K + C*kappa.

In U(A), this exchange relation is generated by an inner odd element
  Theta(gb) = 1/2 sum_{j=1}^n (
      gb_{a1+, bj+} * E_{eps1, del_j, --}
    - gb_{a1+, bj-} * E_{eps1, del_j, -+}
    + gb_{a1-, bj+} * E_{eps1, del_j, +-}
    - gb_{a1-, bj-} * E_{eps1, del_j, ++}
  )
where E_{eps1, del_j, sigma, s} = a_1^sigma b_j^s in g_1.
Under the automorphism v -> v + kappa * [Theta, v], the Lie superalgebra generators
transform by X -> X + kappa * [Theta, X], yielding the deformed bracket:
  [X, Y]_gamma = [X, Y]_0 + kappa * gamma(gb)(X, Y)
where gamma(gb) is the exact 2-cocycle given by the 1-coboundary
  gamma(gb)(X, Y) = (delta f_Theta)(X, Y)
with f_Theta(W) = [W, Theta(gb)].
"""

from fractions import Fraction
from typing import Dict, List, Tuple, Any
from collections import defaultdict
import json
import os
import sys
import sympy as sp

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..")))
try:
    from src.C_generators import get_generators
except ImportError:
    from C_generators import get_generators

DATA_DIR = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "data"))

def get_theta_mapping(n: int) -> Dict[str, Tuple[str, Fraction]]:
    """
    Returns the mapping from gb parameter label to (theta_generator_name, scale_fraction).
    """
    gb_to_theta = {}
    for j in range(1, n + 1):
        gb_to_theta[f"gb_a1p_b{j}p"] = (f"E_eps1_del{j}_mm", Fraction(1, 2))
        gb_to_theta[f"gb_a1p_b{j}m"] = (f"E_eps1_del{j}_mp", Fraction(-1, 2))
        gb_to_theta[f"gb_a1m_b{j}p"] = (f"E_eps1_del{j}_pm", Fraction(1, 2))
        gb_to_theta[f"gb_a1m_b{j}m"] = (f"E_eps1_del{j}_pp", Fraction(-1, 2))
    return gb_to_theta

def compute_gamma_cocycles(n: int) -> Tuple[Dict[Tuple[str, str], Dict[str, Any]], List[str], List[str], Dict[str, int]]:
    """
    Computes gamma(X, Y)^Z as a linear combination of gb parameters for all X, Y in C(n+1).
    """
    even_basis, odd_basis, _, _, _, parity = get_generators(n)
    all_basis = even_basis + odd_basis

    structure_file = os.path.join(DATA_DIR, f"C_{n}_structure.json")
    if not os.path.exists(structure_file):
        raise FileNotFoundError(f"Missing base structure file: {structure_file}")

    with open(structure_file, "r", encoding="utf-8") as f:
        s1 = json.load(f)

    c_base = defaultdict(Fraction)
    for e in s1["structure_constants"]:
        c_base[(e["X"], e["Y"], e["Z"])] = Fraction(e["coeff"])

    gb_to_theta = get_theta_mapping(n)
    gamma_dict = defaultdict(lambda: defaultdict(lambda: sp.Integer(0)))

    # For each elementary parameter, compute the coboundary delta f_Theta
    for param, (theta_gen, scale) in gb_to_theta.items():
        param_sym = sp.Symbol(param)

        def f(X: str) -> Dict[str, Fraction]:
            res = defaultdict(Fraction)
            for Z in all_basis:
                c = c_base.get((X, theta_gen, Z), Fraction(0))
                if c != 0:
                    res[Z] += scale * c
            return res

        for X in all_basis:
            pX = parity[X]
            s1_sign = -1 if pX == 1 else 1
            fX = f(X)
            for Y in all_basis:
                pY = parity[Y]
                s2_sign = - (-1 if ((pX + 1) * pY) % 2 == 1 else 1)
                fY = f(Y)

                res = defaultdict(Fraction)
                # Term 1: (-1)^pX [X, f(Y)]
                for w, cw in fY.items():
                    for Z in all_basis:
                        c = c_base.get((X, w, Z), Fraction(0))
                        if c != 0:
                            res[Z] += s1_sign * cw * c

                # Term 2: - (-1)^{(pX+1)pY} [Y, f(X)]
                for w, cw in fX.items():
                    for Z in all_basis:
                        c = c_base.get((Y, w, Z), Fraction(0))
                        if c != 0:
                            res[Z] += s2_sign * cw * c

                # Term 3: - f([X, Y])
                for w in all_basis:
                    c_XY = c_base.get((X, Y, w), Fraction(0))
                    if c_XY != 0:
                        for Z, cw in f(w).items():
                            res[Z] -= c_XY * cw

                for Z in all_basis:
                    val = res[Z]
                    if val != 0:
                        gamma_dict[(X, Y)][Z] += Fraction(val) * param_sym

    return gamma_dict, even_basis, odd_basis, parity

def build_schema2_json(n: int) -> dict:
    """
    Builds the complete Schema 2 v5.0 dictionary for C(n+1) with inhomogeneous deformation.
    """
    gamma_dict, even_basis, odd_basis, parity = compute_gamma_cocycles(n)
    all_basis = even_basis + odd_basis

    boson_labels = []
    for k in range(1, n + 1):
        boson_labels.extend([f"b_{k}_p", f"b_{k}_m"])

    gb_labels = []
    for sigma in ['p', 'm']:
        for k in range(1, n + 1):
            for s in ['p', 'm']:
                gb_labels.append(f"gb_a1{sigma}_b{k}{s}")

    basis_idx = {g: idx for idx, g in enumerate(all_basis)}
    param_idx = {p: idx for idx, p in enumerate(gb_labels)}

    entries = []
    for (X, Y), targets in gamma_dict.items():
        for Z, expr in targets.items():
            poly_expr = sp.Poly(expr, [sp.Symbol(p) for p in gb_labels])
            for monom, coeff in poly_expr.as_dict().items():
                param_indices = [idx for idx, pow_val in enumerate(monom) if pow_val > 0]
                if len(param_indices) != 1 or monom[param_indices[0]] != 1:
                    raise ValueError(f"Unexpected non-linear term in gamma: {monom} -> {coeff}")
                p_label = gb_labels[param_indices[0]]
                frac_coeff = Fraction(str(coeff))
                coeff_str = str(frac_coeff) if frac_coeff.denominator == 1 else f"{frac_coeff.numerator}/{frac_coeff.denominator}"
                entries.append({
                    "X": X,
                    "Y": Y,
                    "Z": Z,
                    "param": p_label,
                    "coeff": coeff_str,
                    "sign_rule": "graded"
                })

    # Deterministic sort: by X, Y, Z in basis order, then param order
    entries.sort(key=lambda e: (basis_idx[e["X"]], basis_idx[e["Y"]], basis_idx[e["Z"]], param_idx[e["param"]]))

    return {
        "schema_version": "5.0",
        "algebra": {
            "family": "C",
            "m": 1,
            "n": n,
            "cartan_type": f"C({n+1})",
            "alternative_notation": {
                "osp": f"osp(2|{2*n})",
                "dimension_formula": "osp(2m|2n) with m=1: even = 2n^2 + n + 1, odd = 4n, total = 2n^2 + 5n + 1"
            },
            "dimension": {
                "total": 2*n**2 + 5*n + 1,
                "even": 2*n**2 + n + 1,
                "odd": 4*n
            }
        },
        "central_elements": {
            "kappa": {
                "parity": 1,
                "nilpotent_order": 2,
                "relation": "kappa^2 = 0",
                "description": "Odd central nilpotent element carrier of inhomogeneous deformation parameter"
            },
            "K": {
                "parity": 0,
                "scalar_value": 1,
                "description": "Even central identity element (identified with scalar 1; excluded from PBW basis)"
            }
        },
        "basis": {
            "even": even_basis,
            "odd": odd_basis,
            "ordering_convention": "PBW: κ < [odd: ++, +-, -+, --] < [even]"
        },
        "parity": parity,
        "deformation_parameters": {
            "count": 4 * n,
            "matrix_shape": [2, 2 * n],
            "rows": ["a_1_p", "a_1_m"],
            "columns": boson_labels,
            "labels": gb_labels,
            "parity": 1,
            "exchange_relations": "[b_j^s, a_1^sigma] = - gb_{sigma, j, s} * kappa"
        },
        "inhomogeneous_deformation": entries,
        "metadata": {
            "generated_by": "src/C_gamma.py",
            "generation_date": "2026-10-17",
            "references": [
                "Frappat et al. (2000), Dictionary on Lie Algebras and Superalgebras",
                "Bakalov and Sullivan (2017)",
                "docs/math/C_inhomogeneous_definition.md"
            ]
        }
    }

def main():
    os.makedirs(DATA_DIR, exist_ok=True)
    for n in [1, 2, 3]:
        data = build_schema2_json(n)
        filename = os.path.join(DATA_DIR, f"C_{n}_gamma.json")
        with open(filename, "w", encoding="utf-8") as f:
            json.dump(data, f, indent=2)
        print(f"Generated {filename}: {len(data['inhomogeneous_deformation'])} gamma entries")

if __name__ == "__main__":
    main()
