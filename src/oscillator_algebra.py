"""Exact oscillator-algebra engine for C(n+1) = osp(2|2n).

The algebra is generated by
    kappa            : odd, super-central, kappa^2 = 0   (nilpotent extension symbol)
    a_1_p, a_1_m     : standard fermionic pair, {a_1^-, a_1^+} = 1, (a_1^±)^2 = 0
    b_k_p, b_k_m     : bosonic oscillators, [b_k^-, b_l^+] = delta_{kl}
with the (optional) inhomogeneous deformation

    [b_j^s, a_1^sigma] = - gb_{sigma, j, s} * kappa        (C_inhomogeneous_definition.md)

Elements are stored as ``dict[word, coeff]`` where ``word`` is a tuple of symbol
labels in *normal (PBW) order*

    kappa < a_1_p < a_1_m < b_1_p < b_1_m < ... < b_n_p < b_n_m

and ``coeff`` is a sympy expression (rational numbers, or polynomials in the
gb symbols for the deformed algebra).  The graded commutator is
``[X, Y} = X Y - (-1)^{p(X) p(Y)} Y X``.
"""
from __future__ import annotations

from typing import Dict, Tuple

import sympy as sp

Word = Tuple[str, ...]
Element = Dict[Word, sp.Expr]

ZERO = sp.Integer(0)
ONE = sp.Integer(1)


def gb_label(sigma: str, j: int, s: str) -> str:
    """Label of the deformation parameter gb_{a_1^sigma, b_j^s}; sigma, s in {'p','m'}."""
    return f"gb_a1{sigma}_b{j}{s}"


def gb_labels(n: int):
    """All 4n gb labels, ordered as a 2 x 2n matrix (rows a_1_p, a_1_m; cols b_1_p, b_1_m, ...)."""
    return [gb_label(sg, j, s) for sg in "pm" for j in range(1, n + 1) for s in "pm"]


class OscillatorAlgebra:
    def __init__(self, n: int, deformed: bool = False, gb=None):
        self.n = n
        self.deformed = deformed
        syms = ["kappa", "a_1_p", "a_1_m"]
        for k in range(1, n + 1):
            syms += [f"b_{k}_p", f"b_{k}_m"]
        self.symbols = syms
        self.order = {s: i for i, s in enumerate(syms)}
        self.parity = {s: (1 if s in ("kappa", "a_1_p", "a_1_m") else 0) for s in syms}
        if deformed:
            if gb is None:
                gb = {lab: sp.Symbol(lab) for lab in gb_labels(n)}
            self.gb = {k: sp.sympify(v) for k, v in gb.items()}
        else:
            self.gb = {}
        self._cache: Dict[Word, Element] = {}

    # ------------------------------------------------------------------ basics
    def word_parity(self, word: Word) -> int:
        return sum(self.parity[x] for x in word) % 2

    def element_parity(self, elem: Element):
        ps = {self.word_parity(w) for w in elem}
        if len(ps) > 1:
            raise ValueError("inhomogeneous element")
        return ps.pop() if ps else None

    def _bracket_pair(self, x: str, y: str) -> Element:
        """[x, y} for single symbols with order[x] > order[y]."""
        if y == "kappa":  # kappa is super-central
            return {}
        if x == "a_1_m" and y == "a_1_p":  # {a^-, a^+} = 1
            return {(): ONE}
        if x.startswith("b_") and y.startswith("b_"):
            _, kx, sx = x.split("_")
            _, ky, sy = y.split("_")
            if kx == ky and sx == "m" and sy == "p":  # [b^-, b^+] = 1
                return {(): ONE}
            return {}
        if x.startswith("b_") and y.startswith("a_"):
            if not self.deformed:
                return {}
            _, j, s = x.split("_")
            sigma = y.split("_")[2]
            coeff = -self.gb[gb_label(sigma, int(j), s)]
            if coeff == 0:
                return {}
            return {("kappa",): coeff}
        raise ValueError(f"unexpected pair {x}, {y}")

    # ------------------------------------------------------------ normal order
    def normal_order(self, word: Word) -> Element:
        if word in self._cache:
            return self._cache[word]
        result: Element = {word: ONE}
        for i in range(len(word) - 1):
            x, y = word[i], word[i + 1]
            if x == y and self.parity[x] == 1:  # a^2 = 0, kappa^2 = 0
                result = {}
                break
            if self.order[x] > self.order[y]:
                sign = -1 if (self.parity[x] and self.parity[y]) else 1
                result = {}
                swapped = word[:i] + (y, x) + word[i + 2:]
                self._add(result, self.normal_order(swapped), sp.Integer(sign))
                for bw, c in self._bracket_pair(x, y).items():
                    self._add(result, self.normal_order(word[:i] + bw + word[i + 2:]), c)
                break
        self._cache[word] = result
        return result

    @staticmethod
    def _add(target: Element, source: Element, factor) -> None:
        for w, c in source.items():
            target[w] = target.get(w, ZERO) + factor * c

    @staticmethod
    def clean(elem: Element) -> Element:
        out = {}
        for w, c in elem.items():
            c = sp.expand(c)
            if c != 0:
                out[w] = c
        return out

    # --------------------------------------------------------------- algebra
    def add(self, A: Element, B: Element, factor=ONE) -> Element:
        out = dict(A)
        self._add(out, B, factor)
        return self.clean(out)

    def scale(self, A: Element, factor) -> Element:
        return self.clean({w: factor * c for w, c in A.items()})

    def mul(self, A: Element, B: Element) -> Element:
        out: Element = {}
        for wa, ca in A.items():
            for wb, cb in B.items():
                self._add(out, self.normal_order(wa + wb), ca * cb)
        return self.clean(out)

    def bracket(self, A: Element, B: Element) -> Element:
        """Graded commutator [A, B} = AB - (-1)^{p(A)p(B)} BA for homogeneous A, B."""
        pa, pb = self.element_parity(A), self.element_parity(B)
        if pa is None or pb is None:
            return {}
        sign = -1 if (pa and pb) else 1
        out = self.mul(A, B)
        self._add(out, self.mul(B, A), sp.Integer(-sign))
        return self.clean(out)

    # ------------------------------------------------------------- utilities
    @staticmethod
    def split_kappa(elem: Element):
        """Split into (kappa^0 part, kappa^1 part with the leading kappa removed)."""
        k0, k1 = {}, {}
        for w, c in elem.items():
            if w and w[0] == "kappa":
                k1[w[1:]] = c
            else:
                k0[w] = c
        return k0, k1

    @staticmethod
    def from_standard_form(standard_form) -> Element:
        """Build an element from the JSON ``standard_form`` list of {words, coeff}."""
        out: Element = {}
        for term in standard_form:
            w = tuple(term["words"])
            out[w] = out.get(w, ZERO) + sp.Rational(term["coeff"])
        return {w: c for w, c in out.items() if c != 0}
