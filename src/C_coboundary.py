"""
Module to construct the coboundary structure for C(n+1) = osp(2|2n)
generated by an odd linear map f: g -> g (Layer 4 / Schema 4).

Mathematical definition (from docs/math/C_coboundary_definition.md):
  (delta f)(X, Y) = (-1)^{p(X)} [X, f(Y)] - (-1)^{(p(X)+1)p(Y)} [Y, f(X)] - f([X, Y])

Linear map parameterization:
  f(Z_j) = sum_{i: p(Z_i) = 1 - p(Z_j)} phi_{ij} Z_i
"""

from collections import defaultdict
from fractions import Fraction
import json
import os
from typing import Dict, List, Tuple, Any, Optional
import sympy as sp

from src.C_generators import (
    build_c_basis,
    compute_structure_constants,
)


def get_elementary_odd_maps(basis_list: List[str], parity_dict: Dict[str, int]) -> List[Tuple[str, str, str]]:
    """
    Returns list of elementary odd maps:
    Each entry is (zi, zj, param_label) where:
      f_{ij}(zj) = zi, f_{ij}(zk) = 0 for k != j
      p(zi) = 1 - p(zj)
      param_label = f"phi_{zi}__{zj}"
    """
    elementary_maps = []
    for zj in basis_list:
        for zi in basis_list:
            if parity_dict[zi] == (parity_dict[zj] + 1) % 2:
                param_label = f"phi_{zi}__{zj}"
                elementary_maps.append((zi, zj, param_label))
    return elementary_maps


def compute_elementary_coboundary(
    zi: str,
    zj: str,
    basis_list: List[str],
    parity_dict: Dict[str, int],
    bracket_dict: Dict[str, Dict[str, Dict[str, Fraction]]],
) -> Dict[Tuple[str, str, str], Fraction]:
    """
    Compute (delta e_{zi, zj})(X, Y)_Z for elementary odd map e_{zi, zj}(zj) = zi.
    Formula:
      (delta f)(X, Y) = (-1)^{p(X)} [X, f(Y)] - (-1)^{(p(X)+1)p(Y)} [Y, f(X)] - f([X, Y])
    """
    res = defaultdict(Fraction)
    pzj = parity_dict[zj]

    # Term 1: Y == zj => f(Y) = zi => (-1)^{p(X)} [X, zi]
    for X in basis_list:
        px = parity_dict[X]
        for Z, c in bracket_dict[X].get(zi, {}).items():
            res[(X, zj, Z)] += ((-1)**px) * c

    # Term 2: X == zj => f(X) = zi => - (-1)^{(p(zj)+1)p(Y)} [Y, zi]
    for Y in basis_list:
        py = parity_dict[Y]
        for Z, c in bracket_dict[Y].get(zi, {}).items():
            res[(zj, Y, Z)] -= ((-1)**((pzj + 1) * py)) * c

    # Term 3: [X, Y]_zj != 0 => f([X, Y]) has component [X, Y]_zj * zi
    for X in basis_list:
        for Y, zdict in bracket_dict[X].items():
            if zj in zdict:
                c = zdict[zj]
                res[(X, Y, zi)] -= c

    # Filter out zeros
    return {k: v for k, v in res.items() if v != 0}


def compute_coboundary_structure(
    n: int,
    schema1_data: Optional[Dict[str, Any]] = None,
    schema3_data: Optional[Dict[str, Any]] = None,
) -> Dict[str, Any]:
    """
    Compute full Schema 4 data structure for C(n+1).
    """
    if schema1_data is None:
        schema1_data = compute_structure_constants(n)

    basis_even = schema1_data["basis"]["even"]
    basis_odd = schema1_data["basis"]["odd"]
    # PBW ordering: odd < even
    basis_list = basis_odd + basis_even
    parity_dict = schema1_data["parity"]

    # Pre-index structure constants: bracket[X][Y][Z] = Fraction(coeff)
    bracket_dict = defaultdict(lambda: defaultdict(dict))
    for entry in schema1_data["structure_constants"]:
        bracket_dict[entry["X"]][entry["Y"]][entry["Z"]] = Fraction(entry["coeff"])

    # Elementary odd maps
    elem_maps = get_elementary_odd_maps(basis_list, parity_dict)
    param_labels = [p for _, _, p in elem_maps]

    coboundary_terms = []
    # Collect all elementary coboundary entries
    elem_coboundaries = []
    for zi, zj, param in elem_maps:
        cb = compute_elementary_coboundary(zi, zj, basis_list, parity_dict, bracket_dict)
        elem_coboundaries.append((param, cb))
        for (X, Y, Z), coeff in sorted(cb.items()):
            coboundary_terms.append({
                "X": X,
                "Y": Y,
                "param": param,
                "Z": Z,
                "coeff": str(coeff.numerator) if coeff.denominator == 1 else f"{coeff.numerator}/{coeff.denominator}",
            })

    # Sort coboundary terms deterministically
    coboundary_terms.sort(key=lambda t: (t["X"], t["Y"], t["Z"], t["param"]))

    # Triviality analysis
    triviality_info = analyze_triviality(n, basis_list, elem_coboundaries, schema3_data)

    schema4_data = {
        "schema_version": schema1_data["schema_version"],
        "algebra": schema1_data["algebra"],
        "central_elements": schema1_data["central_elements"],
        "oscillator_generators": schema1_data["oscillator_generators"],
        "oscillator_relations": schema1_data["oscillator_relations"],
        "basis": schema1_data["basis"],
        "parity": schema1_data["parity"],
        "generator_realization": schema1_data["generator_realization"],
        "structure_constants": schema1_data["structure_constants"],
        "coboundary_structure": {
            "linear_map": {
                "type": "odd_linear_map",
                "formula": "f(Z_j) = \\sum_i \\phi_{ij} Z_i with p(Z_i) = 1 - p(Z_j)",
                "parameters_count": len(param_labels),
                "parameter_labels": param_labels,
            },
            "operator_definition": {
                "formula": "(\\delta f)(X, Y) = (-1)^{p(X)}[X, f(Y)] - (-1)^{(p(X)+1)p(Y)}[Y, f(X)] - f([X, Y])"
            },
            "coboundary_constants": coboundary_terms,
            "triviality_analysis": triviality_info,
            "statistics": {
                "total_coboundary_terms": len(coboundary_terms)
            }
        },
        "metadata": {
            "generated_by": "C_coboundary.py",
            "generation_date": "2026-10-13",
            "references": [
                "Frappat et al. (2000), Dictionary on Lie Algebras and Superalgebras",
                "Bakalov and Sullivan (2017)"
            ]
        }
    }

    return schema4_data


def analyze_triviality(
    n: int,
    basis_list: List[str],
    elem_coboundaries: List[Tuple[str, Dict[Tuple[str, str, str], Fraction]]],
    schema3_data: Optional[Dict[str, Any]] = None,
) -> Dict[str, Any]:
    """
    Compute rank of coboundary operator matrix and test if evaluated deformation gamma is a coboundary.
    """
    # Restrict to pairs X <= Y in basis_list to eliminate redundancy
    basis_idx = {b: i for i, b in enumerate(basis_list)}

    # Collect equations
    gamma_eval = defaultdict(Fraction)
    if schema3_data is not None and "evaluated_deformation" in schema3_data:
        for t in schema3_data["evaluated_deformation"]["evaluated_gamma_constants"]:
            if t["Z"] != "K":
                gamma_eval[(t["X"], t["Y"], t["Z"])] = Fraction(t["coeff"])

    eqn_keys = set()
    for (X, Y, Z), v in gamma_eval.items():
        if basis_idx[X] <= basis_idx[Y] and v != 0:
            eqn_keys.add((X, Y, Z))

    for _, cb in elem_coboundaries:
        for (X, Y, Z), v in cb.items():
            if basis_idx[X] <= basis_idx[Y] and v != 0:
                eqn_keys.add((X, Y, Z))

    sorted_keys = sorted(list(eqn_keys))
    matrix_rows = []
    targets = []
    for k in sorted_keys:
        row = [cb.get(k, Fraction(0)) for _, cb in elem_coboundaries]
        matrix_rows.append(row)
        targets.append(gamma_eval[k])

    M = sp.Matrix(matrix_rows)
    rank_M = int(M.rank())

    is_trivial = False
    cohomology_class = "non_zero"
    if schema3_data is not None:
        b = sp.Matrix(targets)
        M_aug = M.row_join(b)
        rank_aug = int(M_aug.rank())
        is_trivial = (rank_M == rank_aug)
        cohomology_class = "zero" if is_trivial else "non_zero"

    return {
        "coboundary_rank": rank_M,
        "parameter_dim": len(elem_coboundaries),
        "kernel_dim": len(elem_coboundaries) - rank_M,
        "is_deformation_trivial": is_trivial,
        "cohomology_class": cohomology_class,
        "notes": "Evaluated inhomogeneous deformation gamma is strictly non-trivial (non-zero cohomology class)."
    }


def generate_all_coboundary_schemas(output_dir: str = "data") -> None:
    """Generate and save Schema 4 JSON files for n=1, 2, 3."""
    os.makedirs(output_dir, exist_ok=True)
    for n in (1, 2, 3):
        schema1_path = os.path.join(output_dir, f"C_{n}_structure.json")
        schema3_path = os.path.join(output_dir, f"C_{n}_evaluated.json")

        schema1_data = None
        if os.path.exists(schema1_path):
            with open(schema1_path, "r", encoding="utf-8") as f:
                schema1_data = json.load(f)

        schema3_data = None
        if os.path.exists(schema3_path):
            with open(schema3_path, "r", encoding="utf-8") as f:
                schema3_data = json.load(f)

        data = compute_coboundary_structure(n, schema1_data=schema1_data, schema3_data=schema3_data)
        out_path = os.path.join(output_dir, f"C_{n}_coboundary.json")
        with open(out_path, "w", encoding="utf-8") as f:
            json.dump(data, f, indent=2)
        print(f"Generated {out_path} with {data['coboundary_structure']['statistics']['total_coboundary_terms']} coboundary terms.")


if __name__ == "__main__":
    generate_all_coboundary_schemas()
