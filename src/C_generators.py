"""Structure-constant generator for C(n+1) = osp(2|2n)  (Schema 1, v5.0 extension).

Conventions: handover/notation.md.  Specification: docs/json_schema_specification.md.

The algebra is realised inside the Weyl-Clifford (oscillator) algebra generated by a
standard fermionic pair a_1^± (CAR) and bosons b_k^± (CCR), optionally extended by an
odd central element kappa (kappa^2 = 0) and the inhomogeneous deformation
    [b_k^s, a_1^sigma] = - gb_{a_1^sigma, b_k^s} kappa.
Elements are stored in normally ordered form (dict: word -> Fraction).  Brackets are
computed exactly and decomposed in the basis of g ⊕ C·K by exact linear algebra.

Usage:  python3 src/C_generators.py [--outdir data] [n ...]
"""
from __future__ import annotations

import argparse
import datetime as _dt
import json
import os
import sys
from fractions import Fraction
from itertools import combinations

# --------------------------------------------------------------------------------------
# Oscillator (Weyl-Clifford) algebra
# --------------------------------------------------------------------------------------

KAPPA = "kappa"


class OscillatorAlgebra:
    """Normally ordered Weyl-Clifford algebra for C(n+1), with optional deformation."""

    def __init__(self, n: int, gb: dict | None = None):
        self.n = n
        self.labels = [KAPPA, "a_1_p", "a_1_m"]
        for k in range(1, n + 1):
            self.labels += [f"b_{k}_p", f"b_{k}_m"]
        self.index = {lab: i for i, lab in enumerate(self.labels)}
        self.parity = [1, 1, 1] + [0] * (2 * n)
        # gb: {(sigma, k, s): Fraction}  with sigma, s in {'p','m'}; [b_k^s, a_1^sigma] = -gb kappa
        self.gb = {key: Fraction(v) for key, v in (gb or {}).items() if Fraction(v) != 0}

    # ---- symbol helpers -------------------------------------------------------------
    def is_fermion(self, i: int) -> bool:
        return self.parity[i] == 1

    def boson_info(self, i: int):
        """Return (k, s) for a boson index, else None."""
        if i < 3:
            return None
        k = (i - 3) // 2 + 1
        s = "p" if (i - 3) % 2 == 0 else "m"
        return k, s

    def commutator_xy(self, x: int, y: int) -> dict:
        """[x, y} for symbol indices x > y, returned as element (dict word -> coeff)."""
        if y == 0:  # kappa is central
            return {}
        if x == 2 and y == 1:  # {a^-, a^+} = 1
            return {(): Fraction(1)}
        bx, by = self.boson_info(x), self.boson_info(y)
        if bx is not None and by is None:  # [b_k^s, a_1^sigma] = -gb kappa
            k, s = bx
            sigma = "p" if y == 1 else "m"
            g = self.gb.get((sigma, k, s))
            if g:
                return {(0,): -g}
            return {}
        if bx is not None and by is not None:
            if bx[0] == by[0] and bx[1] == "m" and by[1] == "p":  # [b^-, b^+] = 1
                return {(): Fraction(1)}
            return {}
        return {}

    # ---- normal ordering ------------------------------------------------------------
    def normal_order(self, word: tuple, coeff: Fraction) -> dict:
        result: dict = {}
        stack = [(tuple(word), Fraction(coeff))]
        while stack:
            w, c = stack.pop()
            if c == 0:
                continue
            pos = -1
            for i in range(len(w) - 1):
                if w[i] > w[i + 1]:
                    pos = i
                    break
            if pos < 0:
                # sorted: fermionic squares vanish
                if any(w[i] == w[i + 1] and self.is_fermion(w[i]) for i in range(len(w) - 1)):
                    continue
                result[w] = result.get(w, Fraction(0)) + c
                if result[w] == 0:
                    del result[w]
                continue
            x, y = w[pos], w[pos + 1]
            sign = -1 if (self.parity[x] and self.parity[y]) else 1
            stack.append((w[:pos] + (y, x) + w[pos + 2:], c * sign))
            for term, tc in self.commutator_xy(x, y).items():
                stack.append((w[:pos] + term + w[pos + 2:], c * tc))
        return result

    def element(self, terms) -> dict:
        """Build an element from [(list_of_labels, coeff), ...]."""
        out: dict = {}
        for labels, c in terms:
            word = tuple(self.index[l] for l in labels)
            for w, v in self.normal_order(word, Fraction(c)).items():
                out[w] = out.get(w, Fraction(0)) + v
        return {w: v for w, v in out.items() if v != 0}

    def multiply(self, A: dict, B: dict) -> dict:
        out: dict = {}
        for wa, ca in A.items():
            for wb, cb in B.items():
                for w, v in self.normal_order(wa + wb, ca * cb).items():
                    out[w] = out.get(w, Fraction(0)) + v
        return {w: v for w, v in out.items() if v != 0}

    def word_parity(self, w: tuple) -> int:
        return sum(self.parity[i] for i in w) % 2

    def element_parity(self, A: dict) -> int:
        ps = {self.word_parity(w) for w in A}
        if len(ps) > 1:
            raise ValueError("inhomogeneous element")
        return ps.pop() if ps else 0

    def bracket(self, A: dict, B: dict) -> dict:
        """Graded bracket [A, B} = AB - (-1)^{p(A)p(B)} BA."""
        sign = -1 if (self.element_parity(A) and self.element_parity(B)) else 1
        AB = self.multiply(A, B)
        BA = self.multiply(B, A)
        out = dict(AB)
        for w, v in BA.items():
            out[w] = out.get(w, Fraction(0)) - sign * v
        return {w: v for w, v in out.items() if v != 0}

    @staticmethod
    def add(A: dict, B: dict, cb=Fraction(1)) -> dict:
        out = dict(A)
        for w, v in B.items():
            out[w] = out.get(w, Fraction(0)) + cb * v
        return {w: v for w, v in out.items() if v != 0}

    def split_kappa(self, A: dict):
        """Split A = A0 + kappa*A1 (kappa is always the first symbol in normal order)."""
        A0, A1 = {}, {}
        for w, v in A.items():
            if w and w[0] == 0:
                A1[w[1:]] = v
            else:
                A0[w] = v
        return A0, A1

    def word_str(self, w: tuple) -> str:
        return " ".join(self.labels[i] for i in w) if w else "1"


# --------------------------------------------------------------------------------------
# Basis of C(n+1)
# --------------------------------------------------------------------------------------

def sign_char(s: str) -> str:
    return "+" if s == "p" else "-"


def build_basis(n: int):
    """Return (odd_labels, even_labels, realization dict, roots dict) following notation.md."""
    real = {}
    roots = {}
    odd = []
    for sigma in ("p", "m"):
        for s in ("p", "m"):
            for k in range(1, n + 1):
                lab = f"E_eps1_del{k}_{sigma}{s}"
                odd.append(lab)
                real[lab] = [([f"a_1_{sigma}", f"b_{k}_{s}"], Fraction(1))]
                roots[lab] = ("ε" if sigma == "p" else "-ε") + f"{sign_char(s)}δ_{k}"
    even = []
    # Cartan
    for k in range(1, n + 2):
        lab = f"H_{k}"
        even.append(lab)
        if k == 1:
            real[lab] = [(["a_1_p", "a_1_m"], Fraction(1)), (["b_1_p", "b_1_m"], Fraction(1))]
        elif k <= n:
            real[lab] = [([f"b_{k-1}_p", f"b_{k-1}_m"], Fraction(1)), ([f"b_{k}_p", f"b_{k}_m"], Fraction(-1))]
        else:
            real[lab] = [([f"b_{n}_p", f"b_{n}_m"], Fraction(-1)), ([], Fraction(-1, 2))]
    pairs = list(combinations(range(1, n + 1), 2))
    blocks = [
        [(f"E_2del{k}_p", [f"b_{k}_p", f"b_{k}_p"], f"2δ_{k}") for k in range(1, n + 1)]
        + [(f"E_del{i}_del{j}_pp", [f"b_{i}_p", f"b_{j}_p"], f"δ_{i}+δ_{j}") for i, j in pairs],
        [(f"E_2del{k}_m", [f"b_{k}_m", f"b_{k}_m"], f"-2δ_{k}") for k in range(1, n + 1)]
        + [(f"E_del{i}_del{j}_mm", [f"b_{i}_m", f"b_{j}_m"], f"-δ_{i}-δ_{j}") for i, j in pairs],
        [(f"E_del{i}_del{j}_pm", [f"b_{i}_p", f"b_{j}_m"], f"δ_{i}-δ_{j}") for i, j in pairs],
        [(f"E_del{i}_del{j}_mp", [f"b_{i}_m", f"b_{j}_p"], f"-δ_{i}+δ_{j}") for i, j in pairs],
    ]
    for block in blocks:
        for lab, words, root in block:
            even.append(lab)
            real[lab] = [(words, Fraction(1))]
            roots[lab] = root
    return odd, even, real, roots


def frappat_form(alg: OscillatorAlgebra, terms) -> str:
    def fmt_label(l):
        kind, idx, s = l.split("_")
        return f"{kind}_{idx}^{sign_char(s)}"

    parts = []
    for words, c in terms:
        body = " ".join(fmt_label(w) for w in words)
        if not words:
            body = ""
        c = Fraction(c)
        if body:
            if c == 1:
                txt = body
            elif c == -1:
                txt = f"-{body}"
            else:
                txt = f"{c} {body}"
        else:
            txt = str(c)
        parts.append(txt)
    out = " + ".join(parts)
    return out.replace("+ -", "- ")


# --------------------------------------------------------------------------------------
# Exact decomposition in the basis of g ⊕ C K
# --------------------------------------------------------------------------------------

class Decomposer:
    """Decompose elements of the oscillator algebra in span(basis ∪ {K}) exactly."""

    def __init__(self, alg: OscillatorAlgebra, labels: list, elements: dict, include_K=True):
        self.alg = alg
        self.labels = list(labels) + (["K"] if include_K else [])
        vecs = [dict(elements[l]) for l in labels]
        if include_K:
            vecs.append({(): Fraction(1)})
        monos = sorted({w for v in vecs for w in v})
        self.mono_index = {w: i for i, w in enumerate(monos)}
        m = len(self.labels)
        ncol = len(monos)
        # augmented rows: [vector | identity]  -> RREF gives T with R = T*M
        rows = []
        for r, v in enumerate(vecs):
            row = [Fraction(0)] * (ncol + m)
            for w, c in v.items():
                row[self.mono_index[w]] = c
            row[ncol + r] = Fraction(1)
            rows.append(row)
        pivots = []
        rank = 0
        for col in range(ncol):
            piv = next((r for r in range(rank, m) if rows[r][col] != 0), None)
            if piv is None:
                continue
            rows[rank], rows[piv] = rows[piv], rows[rank]
            pv = rows[rank][col]
            rows[rank] = [x / pv for x in rows[rank]]
            for r in range(m):
                if r != rank and rows[r][col] != 0:
                    f = rows[r][col]
                    rows[r] = [a - f * b for a, b in zip(rows[r], rows[rank])]
            pivots.append(col)
            rank += 1
        if rank != m:
            raise ValueError(f"basis elements are linearly dependent (rank {rank} < {m})")
        self.ncol = ncol
        self.pivots = pivots
        self.R = [row[:ncol] for row in rows]
        self.T = [row[ncol:] for row in rows]

    def decompose(self, A: dict) -> dict:
        """Return {label: coeff}; raise if A is not in the span."""
        t = [Fraction(0)] * self.ncol
        for w, c in A.items():
            if w not in self.mono_index:
                raise ValueError(f"monomial {self.alg.word_str(w)} not in span")
            t[self.mono_index[w]] = c
        d = [t[p] for p in self.pivots]
        # residual check
        resid = list(t)
        for j, dj in enumerate(d):
            if dj != 0:
                for col in range(self.ncol):
                    resid[col] -= dj * self.R[j][col]
        if any(x != 0 for x in resid):
            raise ValueError("element not in span of basis")
        coeffs = {}
        for i, lab in enumerate(self.labels):
            c = sum(d[j] * self.T[j][i] for j in range(len(d)))
            if c != 0:
                coeffs[lab] = c
        return coeffs


# --------------------------------------------------------------------------------------
# Structure constants and Schema 1 JSON
# --------------------------------------------------------------------------------------

def fr(x: Fraction) -> str:
    return str(Fraction(x))


def build_algebra(n: int, gb: dict | None = None):
    alg = OscillatorAlgebra(n, gb)
    odd, even, real, roots = build_basis(n)
    elements = {lab: alg.element(terms) for lab, terms in real.items()}
    return alg, odd, even, real, roots, elements


def compute_structure_constants(n: int):
    """Return (entries, bracket_table) for the undeformed algebra."""
    alg, odd, even, real, roots, elements = build_algebra(n)
    order = odd + even
    dec = Decomposer(alg, order, elements, include_K=True)
    entries = []
    table = {}
    for X in order:
        for Y in order:
            br = alg.bracket(elements[X], elements[Y])
            A0, A1 = alg.split_kappa(br)
            assert not A1, "kappa term in undeformed bracket"
            coeffs = dec.decompose(A0)
            assert "K" not in coeffs, f"bracket [{X},{Y}] has a K component: {coeffs}"
            table[(X, Y)] = coeffs
            for Z in order:  # keep pbw order of Z
                if Z in coeffs:
                    entries.append({"X": X, "Y": Y, "Z": Z, "coeff": fr(coeffs[Z]), "sign_rule": "graded"})
    return entries, table


def algebra_block(n: int) -> dict:
    even = 2 * n * n + n + 1
    odd = 4 * n
    return {
        "family": "C",
        "m": 1,
        "n": n,
        "cartan_type": f"C({n+1})",
        "alternative_notation": {"osp": f"osp(2|{2*n})", "dimension_formula": "osp(2m|2n) with m=1"},
        "dimension_formula": {"even": "2n^2 + n + 1", "odd": "4n", "total": "2n^2 + 5n + 1"},
        "dimension": {"total": even + odd, "even": even, "odd": odd},
        "even_subalgebra": f"so(2) x sp({2*n})",
        "rank": n + 1,
    }


def central_elements_block() -> dict:
    return {
        "kappa": {
            "label": "kappa",
            "parity": 1,
            "relations": "kappa^2 = 0; kappa x = (-1)^{p(x)} x kappa for homogeneous x",
            "role": "odd central element of the extension A = V ⊕ CK ⊕ Cκ; carries the inhomogeneous deformation [X,Y]_γ = [X,Y]_0 + κ γ(X,Y)",
            "in_basis": False,
        },
        "K": {
            "label": "K",
            "parity": 0,
            "relations": "K = 1 (identified with the scalar identity)",
            "role": "even central element; appears as the Z-label of scalar components of γ and f",
            "in_basis": False,
        },
    }


def metadata_block(script: str) -> dict:
    return {
        "generated_by": script,
        "generation_date": _dt.date.today().isoformat(),
        "notation": "handover/notation.md",
        "specification": "docs/json_schema_specification.md",
        "references": [
            "Frappat, Sciarrino, Sorba (2000), Dictionary on Lie Algebras and Superalgebras",
            "Bakalov and Sullivan (2017)",
        ],
    }


def build_schema1(n: int) -> dict:
    alg, odd, even, real, roots, elements = build_algebra(n)
    entries, _ = compute_structure_constants(n)
    bos = [f"b_{k}_{s}" for k in range(1, n + 1) for s in ("p", "m")]
    realizations = {}
    for lab in odd + even:
        terms = real[lab]
        d = {
            "standard_form": [{"words": list(w), "coeff": fr(c)} for w, c in terms],
            "frappat_form": frappat_form(alg, terms),
            "parity": 1 if lab in odd else 0,
        }
        if lab == f"H_{n+1}":
            d["note"] = f"Terminal Cartan; constant required for closure of [E_2del{n}_p, E_2del{n}_m]"
        if lab == "H_1":
            d["note"] = "Contains the so(2) number operator a_1^+ a_1^-; J = a_1^+a_1^- - 1/2 = H_1 - H_2 - ... - H_n + H_{n+1}"
        realizations[lab] = d
    return {
        "schema_version": "5.0",
        "schema_layer": 1,
        "algebra": algebra_block(n),
        "oscillator_generators": {
            "fermions": {
                "m": 1,
                "count": 2,
                "labels": ["a_1_p", "a_1_m"],
                "parity": 1,
                "description": "Standard fermionic pair a_1^± with CAR {a_1^-, a_1^+} = 1",
            },
            "bosons": {
                "n": n,
                "count": 2 * n,
                "labels": bos,
                "parity": 0,
                "description": "Bosonic oscillators b_k^± with k=1,...,n",
            },
        },
        "oscillator_relations": {
            "fermionic_anticommutators": {
                "description": "Canonical anticommutation relations for the standard fermionic pair",
                "relations": {
                    "conjugate_pair": "{a_1^-, a_1^+} = 1",
                    "same_type": "{a_1^±, a_1^±} = 0  (equivalently (a_1^±)^2 = 0)",
                },
            },
            "bosonic_commutators": {
                "description": "Canonical commutation relations for bosonic oscillators",
                "relations": {
                    "same_type": "[b_i^±, b_j^±] = 0 for all i, j",
                    "conjugate_pair": "[b_i^-, b_j^+] = δ_{ij}",
                },
            },
            "mixed_commutators": {
                "boson_fermion": "[b_i^±, a_1^±] = 0  (undeformed; see Schema 2 for the deformation)"
            },
        },
        "central_elements": central_elements_block(),
        "basis": {
            "even": even,
            "odd": odd,
            "ordering_convention": "PBW: kappa < [odd] < [even]  (K = 1 is excluded)",
            "pbw_order": odd + even,
            "cartan": [f"H_{k}" for k in range(1, n + 2)],
            "roots": roots,
        },
        "parity": {lab: (1 if lab in odd else 0) for lab in odd + even},
        "generator_realization": {
            "description": "Normally ordered form in the oscillator algebra",
            "ordering": ", ".join(alg.labels[1:]),
            "realizations": realizations,
        },
        "structure_constants": entries,
        "metadata": metadata_block("src/C_generators.py"),
    }


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("ns", nargs="*", type=int, default=[1, 2, 3])
    ap.add_argument("--outdir", default=os.path.join(os.path.dirname(__file__), "..", "data"))
    args = ap.parse_args(argv)
    os.makedirs(args.outdir, exist_ok=True)
    for n in args.ns:
        schema = build_schema1(n)
        path = os.path.join(args.outdir, f"C_{n}_structure.json")
        with open(path, "w") as fh:
            json.dump(schema, fh, indent=1, ensure_ascii=False)
        d = schema["algebra"]["dimension"]
        print(f"C({n+1}) = osp(2|{2*n}): even {d['even']}, odd {d['odd']}, total {d['total']}, "
              f"{len(schema['structure_constants'])} structure-constant entries -> {os.path.relpath(path)}")


if __name__ == "__main__":
    main()
