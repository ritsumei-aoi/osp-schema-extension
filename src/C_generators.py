"""C(n+1) = osp(2|2n) basis, oscillator algebra and structure-constant generator.

The superalgebra is realized by quadratic elements of the oscillator algebra generated by
    kappa (odd, central, kappa^2 = 0), a_1^+ , a_1^- (odd, CAR), b_k^+ , b_k^- (even, CCR).
Elements are kept in PBW normal form (kappa < a_1_p < a_1_m < b_1_p < b_1_m < ...).
The deformed relation [b_k^s, a_1^sigma] = -gb_{sigma,k,s} kappa is built into the rewriting
rules; with all gb = 0 it reduces to the undeformed algebra.

Usage: python src/C_generators.py   (writes data/C_{n}_structure.json for n = 1, 2, 3)
"""
import json
import sys
from fractions import Fraction as F
from functools import lru_cache
from pathlib import Path

import sympy

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"

# ---------------------------------------------------------------------------
# oscillator letters: 0 = kappa, 1 = a_1_p, 2 = a_1_m, 3 + 2(j-1) + {0,1} = b_j_{p,m}
# ---------------------------------------------------------------------------
KAPPA, AP, AM = 0, 1, 2


def boson_id(j, s):
    return 3 + 2 * (j - 1) + (0 if s == "p" else 1)


def is_odd_letter(x):
    return x <= AM


def letter_label(x):
    if x == KAPPA:
        return "kappa"
    if x == AP:
        return "a_1_p"
    if x == AM:
        return "a_1_m"
    j, r = divmod(x - 3, 2)
    return f"b_{j + 1}_{'p' if r == 0 else 'm'}"


def gb_name(sigma, j, s):
    """Name of gb_{a_1^sigma, b_j^s}: [b_j^s, a_1^sigma] = -gb kappa."""
    return f"gb_a_1_{sigma}_b_{j}_{s}"


def gb_names(n):
    return [gb_name(sg, j, s) for j in range(1, n + 1) for s in "pm" for sg in "pm"]


# ---------------------------------------------------------------------------
# coefficients are dicts {symbol: Fraction}; symbol '' is the scalar part, other symbols are gb's.
# A coefficient never contains a product of two gb's because kappa^2 = 0 kills such terms.
# ---------------------------------------------------------------------------
def cmul(a, b):
    out = {}
    for s1, c1 in a.items():
        for s2, c2 in b.items():
            if s1 and s2:
                continue
            key = s1 or s2
            out[key] = out.get(key, F(0)) + c1 * c2
    return out


def cadd_into(dst, src, factor=F(1)):
    for s, c in src.items():
        v = dst.get(s, F(0)) + c * factor
        if v == 0:
            dst.pop(s, None)
        else:
            dst[s] = v


ONE = {"": F(1)}


@lru_cache(maxsize=None)
def nord(word):
    """Normal-order a word (tuple of letters). Returns {word: coeff-dict}."""
    for i in range(len(word) - 1):
        x, y = word[i], word[i + 1]
        if x < y:
            continue
        pre, post = word[:i], word[i + 2:]
        if x == y:
            if is_odd_letter(x):
                return {}  # a_p^2 = a_m^2 = kappa^2 = 0
            continue
        out = {}
        if y == KAPPA:  # kappa is central: x kappa = (-1)^{|x|} kappa x
            sign = -1 if is_odd_letter(x) else 1
            for w, c in nord(pre + (y, x) + post).items():
                _add(out, w, c, F(sign))
            return out
        if not is_odd_letter(x) and not is_odd_letter(y):  # b b': [b_j^-, b_j^+] = 1
            for w, c in nord(pre + (y, x) + post).items():
                _add(out, w, c, F(1))
            if x == y + 1 and y >= 3 and (y - 3) % 2 == 0:
                for w, c in nord(pre + post).items():
                    _add(out, w, c, F(1))
            return out
        if is_odd_letter(x) and is_odd_letter(y):  # CAR: a_m a_p = -a_p a_m + 1
            for w, c in nord(pre + (y, x) + post).items():
                _add(out, w, c, F(-1))
            if x == AM and y == AP:
                for w, c in nord(pre + post).items():
                    _add(out, w, c, F(1))
            return out
        # x boson (even), y fermion (odd): b a = a b - gb kappa
        assert not is_odd_letter(x) and is_odd_letter(y)
        j, r = divmod(x - 3, 2)
        sym = gb_name("p" if y == AP else "m", j + 1, "p" if r == 0 else "m")
        for w, c in nord(pre + (y, x) + post).items():
            _add(out, w, c, F(1))
        for w, c in nord(pre + (KAPPA,) + post).items():
            _add(out, w, cmul(c, {sym: F(-1)}), F(1))
        return out
    return {word: dict(ONE)}


def _add(out, w, c, factor):
    d = out.setdefault(w, {})
    cadd_into(d, c, factor)
    if not d:
        del out[w]


def pmul(p, q):
    out = {}
    for w1, c1 in p.items():
        for w2, c2 in q.items():
            c12 = cmul(c1, c2)
            if not c12:
                continue
            for w, c in nord(w1 + w2).items():
                _add(out, w, cmul(c12, c), F(1))
    return out


def padd_scaled(p, q, factor):
    out = {w: dict(c) for w, c in p.items()}
    for w, c in q.items():
        _add(out, w, c, F(factor))
    return out


def supercommutator(p, par_p, q, par_q):
    sign = -1 if (par_p and par_q) else 1
    return padd_scaled(pmul(p, q), pmul(q, p), -sign)


