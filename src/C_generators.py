def basis_lists(n):
    even = [f"H_{k}" for k in range(1, n + 2)]
    pairs = [(i, j) for i in range(1, n + 1) for j in range(i + 1, n + 1)]
    even += [f"E_2del{k}_p" for k in range(1, n + 1)]
    even += [f"E_del{i}_del{j}_pp" for i, j in pairs]
    even += [f"E_2del{k}_m" for k in range(1, n + 1)]
    even += [f"E_del{i}_del{j}_mm" for i, j in pairs]
    even += [f"E_del{i}_del{j}_pm" for i, j in pairs]
    even += [f"E_del{i}_del{j}_mp" for i, j in pairs]
    odd = [f"E_eps1_del{k}_{t}" for t in ("pp", "pm", "mp", "mm") for k in range(1, n + 1)]
    return even, odd


def realizations(n):
    """label -> list of (word tuple, Fraction coeff) in PBW oscillator words."""
    r = {}
    N = lambda j: (boson_id(j, "p"), boson_id(j, "m"))
    r["H_1"] = [((AP, AM), F(1)), (N(1), F(1))]
    for k in range(2, n + 1):
        r[f"H_{k}"] = [(N(k - 1), F(1)), (N(k), F(-1))]
    r[f"H_{n + 1}"] = [(N(n), F(-1)), ((), F(-1, 2))]
    for k in range(1, n + 1):
        r[f"E_2del{k}_p"] = [((boson_id(k, "p"),) * 2, F(1))]
        r[f"E_2del{k}_m"] = [((boson_id(k, "m"),) * 2, F(1))]
        for t, (sg, s) in {"pp": ("p", "p"), "pm": ("p", "m"), "mp": ("m", "p"), "mm": ("m", "m")}.items():
            r[f"E_eps1_del{k}_{t}"] = [((AP if sg == "p" else AM, boson_id(k, s)), F(1))]
    for i in range(1, n + 1):
        for j in range(i + 1, n + 1):
            for t in ("pp", "pm", "mp", "mm"):
                w = tuple(sorted((boson_id(i, t[0]), boson_id(j, t[1]))))
                r[f"E_del{i}_del{j}_{t}"] = [(w, F(1))]
    return r


class CAlgebra:
    """C(n+1) basis, realization polynomials, and bracket decomposition."""

    def __init__(self, n):
        self.n = n
        self.even, self.odd = basis_lists(n)
        self.basis = self.even + self.odd
        self.index = {b: i for i, b in enumerate(self.basis)}
        self.parity = {b: 0 for b in self.even}
        self.parity.update({b: 1 for b in self.odd})
        self.real = realizations(n)
        self.poly = {b: {w: {"": c} for w, c in self.real[b]} for b in self.basis}
        # root monomials (single word per root generator) and Cartan block
        self.root_word = {b: self.real[b][0][0] for b in self.basis if not b.startswith("H_")}
        self.word_root = {w: b for b, w in self.root_word.items()}
        cart_words = [(AP, AM)] + [(boson_id(j, "p"), boson_id(j, "m")) for j in range(1, n + 1)] + [()]
        self.cart_words = cart_words
        cols = [self.real[f"H_{k}"] for k in range(1, n + 2)] + [[((), F(1))]]
        M = sympy.zeros(n + 2, n + 2)
        for c, col in enumerate(cols):
            for w, coeff in col:
                M[cart_words.index(w), c] = sympy.Rational(coeff.numerator, coeff.denominator)
        Minv = M.inv()
        self.cart_inv = [[F(int(Minv[r, c].p), int(Minv[r, c].q)) for c in range(n + 2)] for r in range(n + 2)]

    def decompose(self, vec):
        """vec: {word: Fraction}. Returns ({label: Fraction}, K-coefficient). Raises if not in g + CK."""
        out = {}
        rest = {}
        for w, c in vec.items():
            if w in self.word_root:
                out[self.word_root[w]] = c
            elif w in self.cart_words:
                rest[w] = c
            else:
                raise ValueError(f"monomial {w} outside g + K")
        v = [rest.get(w, F(0)) for w in self.cart_words]
        x = [sum(self.cart_inv[r][c] * v[c] for c in range(self.n + 2)) for r in range(self.n + 2)]
        for k in range(self.n + 1):
            if x[k] != 0:
                out[f"H_{k + 1}"] = x[k]
        return out, x[self.n + 1]

    def bracket_poly(self, X, Y):
        return supercommutator(self.poly[X], self.parity[X], self.poly[Y], self.parity[Y])

    def split_bracket(self, X, Y):
        """Returns (undeformed {word: F}, {sym: {word: F}} kappa part with kappa stripped)."""
        res = self.bracket_poly(X, Y)
        und, kap = {}, {}
        for w, c in res.items():
            if w and w[0] == KAPPA:
                for sym, v in c.items():
                    assert sym
                    kap.setdefault(sym, {})[w[1:]] = v
            else:
                assert set(c) == {""}
                und[w] = c[""]
        return und, kap


def structure_table(alg):
    """{(X, Y): {Z: Fraction}} for g (kappa-free part), checked to have no K component."""
    table = {}
    for X in alg.basis:
        for Y in alg.basis:
            und, _ = alg.split_bracket(X, Y)
            comps, k = alg.decompose(und)
            assert k == 0, (X, Y, k)
            if comps:
                table[(X, Y)] = comps
    return table


def gamma_table(alg):
    """Kappa part of [X,Y] in the deformed algebra.

    Returns (gamma, central) with
      gamma[(X,Y)]   = {Z: {gb_symbol: Fraction}}   (g-valued part, gamma_{XYZ})
      central[(X,Y)] = {gb_symbol: Fraction}        (coefficient of kappa*K = kappa, outside g)
    """
    gamma, central = {}, {}
    for X in alg.basis:
        for Y in alg.basis:
            _, kap = alg.split_bracket(X, Y)
            for sym, vec in kap.items():
                comps, k = alg.decompose(vec)
                for Z, c in comps.items():
                    gamma.setdefault((X, Y), {}).setdefault(Z, {})[sym] = c
                if k != 0:
                    central.setdefault((X, Y), {})[sym] = k
    return gamma, central


