def fstr(c):
    c = F(c)
    return str(c.numerator) if c.denominator == 1 else f"{c.numerator}/{c.denominator}"


def frappat_form(words_coeffs):
    terms = []
    for words, c in words_coeffs:
        mono = " ".join(_frappat_letter(x) for x in words) if words else "1"
        terms.append((c, mono))
    out = ""
    for i, (c, mono) in enumerate(terms):
        sign = "-" if c < 0 else "+"
        mag = abs(c)
        body = mono if mag == 1 else (f"{fstr(mag)}" if mono == "1" else f"{fstr(mag)} {mono}")
        out += (f"{'-' if sign == '-' else ''}{body}" if i == 0 else f" {sign} {body}")
    return out


def _frappat_letter(x):
    lab = letter_label(x)  # a_1_p / b_k_m
    head, k, s = lab.split("_")
    return f"{head}_{k}^{'+' if s == 'p' else '-'}"


def schema1(n, alg=None, table=None):
    alg = alg or CAlgebra(n)
    table = table if table is not None else structure_table(alg)
    realization = {}
    for b in alg.basis:
        realization[b] = {
            "standard_form": [{"words": [letter_label(x) for x in w], "coeff": fstr(c)} for w, c in alg.real[b]],
            "frappat_form": frappat_form(alg.real[b]),
            "parity": alg.parity[b],
        }
    realization["H_%d" % (n + 1)]["note"] = "Terminal Cartan; constant term makes the algebra close without a central term"
    sc = []
    for X in alg.basis:
        for Y in alg.basis:
            comps = table.get((X, Y), {})
            for Z in sorted(comps, key=lambda z: alg.index[z]):
                sc.append({"X": X, "Y": Y, "Z": Z, "coeff": fstr(comps[Z]), "sign_rule": "graded"})
    even, odd = alg.even, alg.odd
    bos_labels = [f"b_{j}_{s}" for j in range(1, n + 1) for s in "pm"]
    return {
        "schema_version": "5.0",
        "algebra": {
            "family": "C",
            "m": 1,
            "n": n,
            "cartan_type": f"C({n + 1})",
            "alternative_notation": {"osp": f"osp(2|{2 * n})", "dimension_formula": "osp(2m|2n) with m=1"},
            "dimension_formula": {"even": "2n^2+n+1", "odd": "4n", "total": "2n^2+5n+1"},
            "dimension": {"total": len(even) + len(odd), "even": len(even), "odd": len(odd)},
        },
        "oscillator_generators": {
            "fermions": {
                "m": 1,
                "count": 2,
                "labels": ["a_1_p", "a_1_m"],
                "parity": 1,
                "description": "Standard fermionic pair a_1^+, a_1^- (CAR)",
            },
            "bosons": {
                "count": 2 * n,
                "n": n,
                "labels": bos_labels,
                "parity": 0,
                "description": "Bosonic oscillators b_k^±, k=1..n",
            },
        },
        "oscillator_relations": {
            "standard_fermion_anticommutators": {
                "description": "CAR for the standard fermionic pair",
                "relations": {"conjugate_pair": "{a_1^-, a_1^+} = 1", "nilpotent": "(a_1^+)^2 = (a_1^-)^2 = 0"},
            },
            "bosonic_commutators": {
                "description": "Canonical commutation relations for bosonic oscillators",
                "relations": {"same_type": "[b_i^±, b_j^±] = 0 for all i, j", "conjugate_pair": "[b_i^-, b_j^+] = δ_{ij}"},
            },
            "mixed_commutators": {
                "boson_fermion": "[b_i^s, a_1^σ] = 0 (undeformed; deformed: = -gb_{σ,i,s} κ, see Schema 2)"
            },
        },
        "central_elements": {
            "kappa": {
                "parity": 1,
                "relation": "kappa^2 = 0",
                "central": True,
                "description": "Odd nilpotent central element; carries the deformation",
            },
            "K": {
                "parity": 0,
                "relation": "K = 1",
                "central": True,
                "description": "Even central identity (Bakalov-Sullivan); the scalar 1, not a basis element",
            },
        },
        "basis": {
            "even": even,
            "odd": odd,
            "ordering_convention": "PBW: κ < [odd] < [even]  (K = 1 is excluded)",
        },
        "parity": dict(alg.parity),
        "generator_realization": {
            "description": "Standard form with PBW ordering",
            "ordering": "a_1_p, a_1_m, " + ", ".join(bos_labels),
            "realizations": realization,
        },
        "structure_constants": sc,
        "metadata": {
            "generated_by": "src/C_generators.py",
            "generation_date": "2026-10-06",
            "references": [
                "Frappat et al. (2000), Dictionary on Lie Algebras and Superalgebras",
                "Bakalov and Sullivan (2017)",
            ],
        },
    }


def write_json(path, obj):
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w") as fh:
        json.dump(obj, fh, indent=1, ensure_ascii=False)
        fh.write("\n")


def main(ns=(1, 2, 3)):
    for n in ns:
        write_json(DATA / f"C_{n}_structure.json", schema1(n))
        print(f"wrote C_{n}_structure.json")


if __name__ == "__main__":
    main()
